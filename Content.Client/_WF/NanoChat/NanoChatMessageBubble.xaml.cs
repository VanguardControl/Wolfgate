using Content.Client._WF.WolfChem.Narcotics;
using Content.Shared._WF.NanoChat;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.NanoChat;

/// <summary>
/// One message: own messages on the right in green, others on the left in grey, subtle ones in purple. Its effect sets
/// how the text is drawn, and the reader's high colours it as it does chat.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NanoChatMessageBubble : BoxContainer
{
    public static readonly Color OwnMessageColor = Color.FromHex("#173717d9");
    public static readonly Color OtherMessageColor = Color.FromHex("#252525d9");
    public static readonly Color OwnSubtleColor = Color.FromHex("#3f1f5ed9");
    public static readonly Color OtherSubtleColor = Color.FromHex("#2d2140d9");
    public static readonly Color SubtleBorderColor = Color.FromHex("#8a5cc480");
    public static readonly Color BorderColor = Color.FromHex("#40404066");
    public static readonly Color TextColor = Color.FromHex("#dcdcdc");
    public static readonly Color ErrorColor = Color.FromHex("#cc3333");
    public static readonly Color WhisperColor = Color.FromHex("#9c9c9c");

    [Dependency] private IEntityManager _entMan = default!;

    public NanoChatMessageBubble()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    /// <summary>Shows a message; a group chat names the sender above others' messages.</summary>
    public void SetMessage(NanoChatMessage message, bool isOwnMessage, bool showSender = false)
    {
        SenderLabel.Visible = showSender && !isOwnMessage && !string.IsNullOrEmpty(message.SenderName);
        SenderLabel.Text = message.SenderName;

        if (MessagePanel.PanelOverride is not StyleBoxFlat style)
            return;

        style.BackgroundColor = (isOwnMessage, message.Subtle) switch
        {
            (true, true) => OwnSubtleColor,
            (false, true) => OtherSubtleColor,
            (true, false) => OwnMessageColor,
            (false, false) => OtherMessageColor,
        };
        style.BorderColor = message.Subtle ? SubtleBorderColor : BorderColor;

        SetText(message);

        DeliveryFailedLabel.Visible = isOwnMessage && message.DeliveryFailed;
        DeliveryFailedLabel.Modulate = ErrorColor;

        MessageContainer.RemoveAllChildren();
        if (isOwnMessage)
        {
            MessageContainer.AddChild(FlexSpace);
            MessageContainer.AddChild(MessageBox);
            MessageContainer.AddChild(RightSpacer);
        }
        else
        {
            MessageContainer.AddChild(LeftSpacer);
            MessageContainer.AddChild(MessageBox);
            MessageContainer.AddChild(FlexSpace);
        }
    }

    private void SetText(NanoChatMessage message)
    {
        var animated = message.Effect is NanoChatEffect.Shake or NanoChatEffect.Wave or NanoChatEffect.Rainbow;
        MessageText.Visible = !animated;
        EffectText.Visible = animated;
        if (animated)
        {
            EffectText.TextColor = TextColor;
            EffectText.SetText(message.Content, message.Effect);
            return;
        }

        var markup = FormattedMessage.EscapeText(message.Content);
        var seed = HashCode.Combine(message.Timestamp, message.SenderId);
        if (_entMan.System<WFDrugChatSystem>().DistortMarkup(markup, seed) is { } seen)
            markup = seen;

        markup = message.Effect switch
        {
            NanoChatEffect.Loud => $"[head=3]{markup}[/head]",
            NanoChatEffect.Whisper => $"[italic][color={WhisperColor.ToHex()}]{markup}[/color][/italic]",
            _ => markup,
        };

        MessageText.SetMessage(FormattedMessage.FromMarkupPermissive(markup));
        MessageText.Modulate = TextColor;
    }
}
