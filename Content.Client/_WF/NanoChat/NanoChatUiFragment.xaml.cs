using System.Linq;
using System.Numerics;
using Content.Shared._WF.NanoChat;
using Content.Shared.Access.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WF.NanoChat;

/// <summary>
/// The NanoChat app: chats on the left, the open chat on the right, the number directory behind a button. Group chats
/// show who sent each message and have a members window.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NanoChatUiFragment : BoxContainer
{
    [Dependency] private IGameTiming _timing = default!;

    private const string DangerClass = "Danger";

    private readonly NewChatPopup _newChatPopup = new();
    private readonly EditChatPopup _editChatPopup = new();
    private readonly NewGroupPopup _newGroupPopup = new();
    private readonly GroupMembersPopup _membersPopup = new();
    private NanoChatGroupInfo? _group;
    private uint? _currentChat;
    private uint? _pendingChat;
    private uint _ownNumber;
    private bool _notificationsMuted;
    private Dictionary<uint, NanoChatRecipient> _recipients = new();
    private Dictionary<uint, List<NanoChatMessage>> _messages = new();
    private HashSet<uint> _mutedChats = new();

    /// <summary>An action for the server: type, number, text or name, job.</summary>
    public event Action<NanoChatUiMessageType, uint?, string?, string?>? OnMessageSent;

    /// <summary>A group action for the server: type, group, name, numbers.</summary>
    public event Action<NanoChatUiMessageType, uint?, string?, List<uint>?>? OnGroupAction;

    /// <summary>Whether messages are sent subtle, out of ghosts' sight. Stays on until toggled off.</summary>
    public bool Subtle => SubtleButton.Pressed;

    /// <summary>The effect for the next message; it goes back to none once sent.</summary>
    public NanoChatEffect Effect => (NanoChatEffect) EffectButton.SelectedId;

    public NanoChatUiFragment()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        SetupEventHandlers();
    }

    private void SetupEventHandlers()
    {
        _newChatPopup.OnChatCreated += (number, name, job) =>
            OnMessageSent?.Invoke(NanoChatUiMessageType.NewChat, number, name, job);

        _editChatPopup.OnContactEdited += (number, name, job) =>
            OnMessageSent?.Invoke(NanoChatUiMessageType.EditChat, number, name, job);

        NewChatButton.OnPressed += _ =>
        {
            _newChatPopup.ClearInputs();
            _newChatPopup.OpenCentered();
        };

        NewGroupButton.OnPressed += _ => _newGroupPopup.Open(Contacts());
        _newGroupPopup.OnGroupCreated += (name, members) =>
            OnGroupAction?.Invoke(NanoChatUiMessageType.CreateGroup, null, name, members);

        MembersButton.OnPressed += _ =>
        {
            if (_group == null)
                return;

            _membersPopup.Update(_group, _ownNumber, Contacts());
            _membersPopup.OpenCentered();
        };
        _membersPopup.OnRename += name => GroupAction(NanoChatUiMessageType.RenameGroup, name, null);
        _membersPopup.OnKick += number => GroupAction(NanoChatUiMessageType.KickMember, null, new List<uint> { number });
        _membersPopup.OnAdd += number => GroupAction(NanoChatUiMessageType.AddMembers, null, new List<uint> { number });
        _membersPopup.OnLeave += () =>
        {
            GroupAction(NanoChatUiMessageType.LeaveGroup, null, null);
            _membersPopup.Close();
        };

        MuteChatButton.OnPressed += _ =>
        {
            if (_currentChat is not { } currentChat)
                return;

            if (!_mutedChats.Remove(currentChat))
                _mutedChats.Add(currentChat);

            UpdateMuteChatButton();
            OnMessageSent?.Invoke(NanoChatUiMessageType.ToggleMuteChat, currentChat, null, null);
        };

        MuteButton.OnPressed += _ =>
        {
            _notificationsMuted = !_notificationsMuted;
            UpdateMuteButton();
            OnMessageSent?.Invoke(NanoChatUiMessageType.ToggleMute, null, null, null);
        };

        MessageInput.OnTextChanged += args =>
        {
            var length = args.Text.Length;
            SendButton.Disabled = string.IsNullOrWhiteSpace(args.Text)
                || length > NanoChatMessage.MaxContentLength
                || _currentChat == null && _pendingChat == null;

            var tooLong = length > NanoChatMessage.MaxContentLength;
            CharacterCount.Visible = tooLong;
            CharacterCount.SetOnlyStyleClass(tooLong ? DangerClass : "LabelSubText");
            if (tooLong)
            {
                CharacterCount.Text = Loc.GetString("nano-chat-message-too-long",
                    ("current", length),
                    ("max", NanoChatMessage.MaxContentLength));
            }
        };

        LookupButton.OnPressed += _ => ToggleView();
        LookupView.OnStartChat += contact =>
        {
            OnMessageSent?.Invoke(NanoChatUiMessageType.NewChat, contact.Number, contact.Name, contact.JobTitle);
            SelectChat(contact.Number);
            ToggleView();
        };

        LookupView.OnListNumberToggled += () =>
            OnMessageSent?.Invoke(NanoChatUiMessageType.ToggleListNumber, null, null, null);

        foreach (var effect in Enum.GetValues<NanoChatEffect>())
        {
            EffectButton.AddItem(Loc.GetString($"nano-chat-effect-{effect.ToString().ToLowerInvariant()}"), (int) effect);
        }

        EffectButton.OnItemSelected += args => EffectButton.SelectId(args.Id);

        SubtleButton.OnToggled += args => MessageInput.PlaceHolder =
            Loc.GetString(args.Pressed ? "nano-chat-subtle-placeholder" : "nano-chat-message-placeholder");

        MessageInput.OnTextEntered += _ => SendMessage();
        SendButton.OnPressed += _ => SendMessage();
        EditChatButton.OnPressed += _ => BeginEditChat();
        DeleteChatButton.OnPressed += _ => DeleteCurrentChat();
    }

    /// <summary>The player's contacts, without groups.</summary>
    private IEnumerable<NanoChatRecipient> Contacts()
    {
        return _recipients.Values.Where(r => !SharedNanoChatSystem.IsGroup(r.Number)).OrderBy(r => r.Name);
    }

    private void GroupAction(NanoChatUiMessageType type, string? name, List<uint>? numbers)
    {
        if (_group is { } group && (_pendingChat ?? _currentChat) == group.Id)
            OnGroupAction?.Invoke(type, group.Id, name, numbers);
    }

    private void ToggleView()
    {
        ChatView.Visible = !ChatView.Visible;
        LookupView.Visible = !ChatView.Visible;
        LookupButton.Pressed = LookupView.Visible;
    }

    private void SendMessage()
    {
        var activeChat = _pendingChat ?? _currentChat;
        if (activeChat is not { } chat || string.IsNullOrWhiteSpace(MessageInput.Text))
            return;

        var content = MessageInput.Text.Trim();
        if (content.Length > NanoChatMessage.MaxContentLength)
            content = content[..NanoChatMessage.MaxContentLength];

        // Show it at once; the server's state replaces it.
        if (!_messages.TryGetValue(chat, out var messages))
        {
            messages = new List<NanoChatMessage>();
            _messages[chat] = messages;
        }

        messages.Add(new NanoChatMessage(_timing.CurTime, content, _ownNumber, subtle: Subtle) { Effect = Effect });
        UpdateMessages(_messages);

        OnMessageSent?.Invoke(NanoChatUiMessageType.SendMessage, chat, content, null);
        EffectButton.SelectId((int) NanoChatEffect.None);
        MessageInput.Text = string.Empty;
        SendButton.Disabled = true;
    }

    private void SelectChat(uint number)
    {
        if (_currentChat == number && _pendingChat == null)
            return;

        _pendingChat = number;
        if (_recipients.TryGetValue(number, out var recipient))
        {
            recipient.HasUnread = false;
            _recipients[number] = recipient;
            UpdateChatList(_recipients);
        }

        OnMessageSent?.Invoke(NanoChatUiMessageType.SelectChat, number, null, null);
        UpdateCurrentChat();
        UpdateMessages(_messages);
    }

    private void DeleteCurrentChat()
    {
        if ((_pendingChat ?? _currentChat) is { } chat)
            OnMessageSent?.Invoke(NanoChatUiMessageType.DeleteChat, chat, null, null);
    }

    private void BeginEditChat()
    {
        if (_currentChat is not { } currentChat || !_recipients.TryGetValue(currentChat, out var recipient))
            return;

        _editChatPopup.ClearInputs();
        _editChatPopup.SetNumberInput(SharedNanoChatSystem.FormatNumber(recipient.Number));
        _editChatPopup.SetNameInput(recipient.Name);
        _editChatPopup.SetJobInput(recipient.JobTitle ?? string.Empty);
        _editChatPopup.OpenCentered();
    }

    private void UpdateChatList(Dictionary<uint, NanoChatRecipient> recipients)
    {
        ChatList.RemoveAllChildren();
        _recipients = recipients;

        NoChatsLabel.Visible = recipients.Count == 0;
        ChatList.AddChild(NoChatsLabel);

        foreach (var (number, recipient) in recipients.OrderBy(r => r.Value.Name))
        {
            var entry = new NanoChatEntry();
            var isSelected = _pendingChat == number || _pendingChat == null && _currentChat == number;
            entry.SetRecipient(recipient, number, isSelected);
            entry.OnPressed += SelectChat;
            ChatList.AddChild(entry);
        }
    }

    private void UpdateCurrentChat()
    {
        var activeChat = _pendingChat ?? _currentChat;
        var hasActiveChat = activeChat != null;

        var isGroup = activeChat is { } open && SharedNanoChatSystem.IsGroup(open);
        var group = _group is { } info && info.Id == activeChat ? info : null;

        MessagesScroll.Visible = hasActiveChat;
        CurrentChatName.Visible = !hasActiveChat;
        MessageInputContainer.Visible = hasActiveChat;
        DeleteChatButton.Visible = hasActiveChat && group is not { IsCompany: true };
        DeleteChatButton.ToolTip = Loc.GetString(isGroup ? "nano-chat-group-leave" : "nano-chat-delete");
        EditChatButton.Visible = hasActiveChat && !isGroup;
        MembersButton.Visible = group != null;
        ChatHeaderLabel.Visible = hasActiveChat;

        if (group != null)
        {
            ChatHeaderLabel.Text = Loc.GetString("nano-chat-group-header", ("name", group.Name), ("count", group.Members.Count));
        }
        else if (activeChat is { } chat && _recipients.TryGetValue(chat, out var recipient))
        {
            ChatHeaderLabel.Text = string.IsNullOrEmpty(recipient.JobTitle)
                ? recipient.Name
                : Loc.GetString("nano-chat-new-message-title-recipient",
                    ("sender", recipient.Name), ("jobTitle", recipient.JobTitle));
        }
        else
        {
            ChatHeaderLabel.Text = activeChat is { } number ? $"#{SharedNanoChatSystem.FormatNumber(number)}" : string.Empty;
        }
    }

    private void UpdateMessages(Dictionary<uint, List<NanoChatMessage>> messages)
    {
        _messages = messages;
        MessageList.RemoveAllChildren();

        var activeChat = _pendingChat ?? _currentChat;
        if (activeChat is not { } chat || !messages.TryGetValue(chat, out var chatMessages))
            return;

        var isGroup = SharedNanoChatSystem.IsGroup(chat);
        foreach (var message in chatMessages)
        {
            var bubble = new NanoChatMessageBubble();
            bubble.SetMessage(message, message.SenderId == _ownNumber, isGroup);
            MessageList.AddChild(bubble);
            MessageList.AddChild(new Control { MinSize = new Vector2(0, 4) });
        }

        MessageList.InvalidateMeasure();
        MessagesScroll.InvalidateMeasure();
        MessagesScroll.SetScrollValue(new Vector2(0, float.MaxValue));
    }

    private void UpdateMuteButton()
    {
        BellMutedIcon.Visible = _notificationsMuted;
        BellIcon.Visible = !_notificationsMuted;
    }

    private void UpdateMuteChatButton()
    {
        var muted = _currentChat is { } currentChat && _mutedChats.Contains(currentChat);
        BellMutedIconContact.Visible = muted;
        BellIconContact.Visible = !muted;
    }

    public void UpdateState(NanoChatUiState state)
    {
        _ownNumber = state.OwnNumber;
        _notificationsMuted = state.NotificationsMuted;
        _mutedChats = state.MutedChats;
        OwnNumberLabel.Text = state.OwnNumber == 0
            ? Loc.GetString("nano-chat-no-card")
            : $"#{SharedNanoChatSystem.FormatNumber(state.OwnNumber)}";
        UpdateMuteButton();

        var atLimit = state.Recipients.Count >= state.MaxRecipients;
        NewChatButton.Disabled = atLimit;
        NewChatButton.ToolTip = atLimit
            ? Loc.GetString("nano-chat-max-recipients")
            : Loc.GetString("nano-chat-new-chat");

        // The server has answered any selection by now; its open chat wins.
        _pendingChat = null;
        _currentChat = state.CurrentChat;
        _group = state.Group;
        if (_membersPopup.IsOpen)
        {
            if (_group != null)
                _membersPopup.Update(_group, _ownNumber, state.Recipients.Values
                    .Where(r => !SharedNanoChatSystem.IsGroup(r.Number))
                    .OrderBy(r => r.Name));
            else
                _membersPopup.Close();
        }

        UpdateChatList(state.Recipients);
        UpdateCurrentChat();
        UpdateMuteChatButton();
        UpdateMessages(state.Messages);
        LookupView.UpdateContactList(state);
    }
}
