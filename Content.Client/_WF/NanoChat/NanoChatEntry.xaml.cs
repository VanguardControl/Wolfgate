using Content.Shared._WF.NanoChat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.NanoChat;

/// <summary>One chat in the chat list.</summary>
[GenerateTypedNameReferences]
public sealed partial class NanoChatEntry : BoxContainer
{
    /// <summary>Raised with the chat's number when it is clicked.</summary>
    public event Action<uint>? OnPressed;

    private uint _number;

    public NanoChatEntry()
    {
        RobustXamlLoader.Load(this);
        ChatButton.OnPressed += _ => OnPressed?.Invoke(_number);
    }

    public void SetRecipient(NanoChatRecipient recipient, uint number, bool isSelected)
    {
        _number = number;
        NameLabel.Text = recipient.Name;
        JobLabel.Text = recipient.JobTitle ?? string.Empty;
        JobLabel.Visible = !string.IsNullOrWhiteSpace(recipient.JobTitle);
        UnreadIndicator.Visible = recipient.HasUnread;
        ChatButton.ModulateSelfOverride = isSelected ? NanoChatMessageBubble.OwnMessageColor : null;
    }
}
