using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared._WF.NanoChat;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.NanoChat;

/// <summary>The directory: every listed number, with a button to start a chat, and whether to list one's own.</summary>
[GenerateTypedNameReferences]
public sealed partial class NanoChatLookupView : PanelContainer
{
    private static readonly Color EvenRowColor = Color.FromHex("#1b1b1e");
    private static readonly Color OddRowColor = Color.FromHex("#25252a");

    /// <summary>Raised with the contact whose chat button was pressed.</summary>
    public event Action<NanoChatRecipient>? OnStartChat;

    /// <summary>Raised when the player lists or unlists their number.</summary>
    public event Action? OnListNumberToggled;

    public NanoChatLookupView()
    {
        RobustXamlLoader.Load(this);
        ListNumberCheck.OnToggled += _ => OnListNumberToggled?.Invoke();
    }

    public void UpdateContactList(NanoChatUiState state)
    {
        ListNumberCheck.Pressed = state.ListNumber;
        ListNumberCheck.Disabled = state.OwnNumber == 0;
        ContactsList.RemoveAllChildren();
        if (state.Contacts is not { } contacts)
        {
            ContactsList.AddChild(new Label { Text = Loc.GetString("nano-chat-look-up-no-server") });
            return;
        }

        for (var i = 0; i < contacts.Count; i++)
        {
            ContactsList.AddChild(ContactRow(contacts[i], state, i % 2 == 0));
        }
    }

    private PanelContainer ContactRow(NanoChatRecipient contact, NanoChatUiState state, bool even)
    {
        var row = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = even ? EvenRowColor : OddRowColor },
        };

        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(4, 0) };
        line.AddChild(new Label
        {
            Text = string.IsNullOrEmpty(contact.JobTitle)
                ? contact.Name
                : Loc.GetString("nano-chat-new-message-title-recipient", ("sender", contact.Name), ("jobTitle", contact.JobTitle)),
            HorizontalExpand = true,
            ClipText = true,
        });
        line.AddChild(new Label
        {
            Text = $"#{SharedNanoChatSystem.FormatNumber(contact.Number)}",
            Margin = new Thickness(0, 0, 8, 0),
        });

        var start = new Button
        {
            Text = "+",
            MinSize = new Vector2(32, 32),
            MaxSize = new Vector2(32, 32),
            ToolTip = Loc.GetString("nano-chat-new-chat"),
            Disabled = contact.Number == state.OwnNumber
                || state.Recipients.ContainsKey(contact.Number)
                || state.Recipients.Count >= state.MaxRecipients,
        };
        start.AddStyleClass(StyleBase.ButtonOpenBoth);
        start.OnPressed += _ => OnStartChat?.Invoke(contact);
        line.AddChild(start);

        row.AddChild(line);
        return row;
    }
}
