using System.Linq;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared._WF.NanoChat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.NanoChat;

/// <summary>A group's members. Its owner renames it, adds contacts and kicks members; anyone may leave a room.</summary>
[GenerateTypedNameReferences]
public sealed partial class GroupMembersPopup : DefaultWindow
{
    public event Action<string>? OnRename;
    public event Action<uint>? OnKick;
    public event Action<uint>? OnAdd;
    public event Action? OnLeave;

    public GroupMembersPopup()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(3);

        RenameButton.OnPressed += _ => Rename();
        NameInput.OnTextEntered += _ => Rename();
        NameInput.OnTextChanged += args =>
        {
            if (args.Text.Length > NewGroupPopup.MaxNameLength)
                NameInput.Text = args.Text[..NewGroupPopup.MaxNameLength];
        };
        LeaveButton.OnPressed += _ => OnLeave?.Invoke();
    }

    private void Rename()
    {
        if (!string.IsNullOrWhiteSpace(NameInput.Text))
            OnRename?.Invoke(NameInput.Text.Trim());
    }

    /// <summary>Shows a group as the player with this number sees it, with their contacts to add.</summary>
    public void Update(NanoChatGroupInfo group, uint ownNumber, IEnumerable<NanoChatRecipient> contacts)
    {
        var manages = !group.IsCompany && group.Owner == ownNumber;
        Title = group.Name;
        RenameRow.Visible = manages;
        if (!NameInput.HasKeyboardFocus())
            NameInput.Text = group.Name;

        CompanyNote.Visible = group.IsCompany;
        LeaveButton.Visible = !group.IsCompany;

        MemberList.RemoveAllChildren();
        foreach (var member in group.Members)
        {
            var text = $"{member.Name} (#{SharedNanoChatSystem.FormatNumber(member.Number)})";
            if (member.Number == group.Owner)
                text = Loc.GetString("nano-chat-group-owner", ("member", text));

            Button? kick = null;
            if (manages && member.Number != ownNumber)
            {
                var number = member.Number;
                kick = new Button { Text = Loc.GetString("nano-chat-group-kick") };
                kick.AddStyleClass(StyleBase.ButtonCaution);
                kick.OnPressed += _ => OnKick?.Invoke(number);
            }

            MemberList.AddChild(Row(text, kick));
        }

        AddSection.Visible = manages;
        AddList.RemoveAllChildren();
        if (!manages)
            return;

        var inGroup = group.Members.Select(m => m.Number).ToHashSet();
        foreach (var contact in contacts.Where(c => !inGroup.Contains(c.Number)))
        {
            var number = contact.Number;
            var add = new Button
            {
                Text = "+",
                MinSize = new Vector2(32, 0),
                ToolTip = Loc.GetString("nano-chat-group-add"),
            };
            add.OnPressed += _ => OnAdd?.Invoke(number);
            AddList.AddChild(Row($"{contact.Name} (#{SharedNanoChatSystem.FormatNumber(number)})", add));
        }
    }

    private static BoxContainer Row(string text, Button? action)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(0, 1) };
        row.AddChild(new Label { Text = text, HorizontalExpand = true, ClipText = true, VerticalAlignment = VAlignment.Center });
        if (action != null)
            row.AddChild(action);

        return row;
    }
}
