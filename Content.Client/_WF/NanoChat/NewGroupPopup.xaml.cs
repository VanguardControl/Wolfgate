using System.Linq;
using Content.Shared._WF.NanoChat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.NanoChat;

/// <summary>Makes a group: a name and any of the player's contacts.</summary>
[GenerateTypedNameReferences]
public sealed partial class NewGroupPopup : DefaultWindow
{
    /// <summary>The longest group name, as the server cuts it.</summary>
    public const int MaxNameLength = 32;

    /// <summary>Raised with the group's name and the numbers picked.</summary>
    public event Action<string, List<uint>>? OnGroupCreated;

    private readonly Dictionary<uint, CheckBox> _picks = new();

    public NewGroupPopup()
    {
        RobustXamlLoader.Load(this);
        ContentsContainer.Margin = new Thickness(3);

        CancelButton.OnPressed += _ => Close();
        CreateButton.OnPressed += _ => Create();
        NameInput.OnTextEntered += _ => Create();
        NameInput.OnTextChanged += args =>
        {
            if (args.Text.Length > MaxNameLength)
                NameInput.Text = args.Text[..MaxNameLength];

            CreateButton.Disabled = string.IsNullOrWhiteSpace(NameInput.Text);
        };
    }

    /// <summary>Clears the form and lists the contacts to pick from.</summary>
    public void Open(IEnumerable<NanoChatRecipient> contacts)
    {
        NameInput.Text = string.Empty;
        CreateButton.Disabled = true;
        ContactList.RemoveAllChildren();
        _picks.Clear();

        foreach (var contact in contacts)
        {
            var pick = new CheckBox
            {
                Text = $"{contact.Name} (#{SharedNanoChatSystem.FormatNumber(contact.Number)})",
            };
            _picks[contact.Number] = pick;
            ContactList.AddChild(pick);
        }

        NoContactsLabel.Visible = _picks.Count == 0;
        OpenCentered();
        NameInput.GrabKeyboardFocus();
    }

    private void Create()
    {
        if (CreateButton.Disabled)
            return;

        var members = _picks.Where(p => p.Value.Pressed).Select(p => p.Key).ToList();
        OnGroupCreated?.Invoke(NameInput.Text.Trim(), members);
        Close();
    }
}
