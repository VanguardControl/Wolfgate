using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Traits.UI;

[GenerateTypedNameReferences]
public sealed partial class TraitCategory : PanelContainer
{
    [Dependency] private ILocalizationManager _loc = default!;

    public string CategoryId { get; }

    public TraitCategoryPrototype? Prototype { get; }

    public IReadOnlyList<TraitEntry> Entries => _entries;

    private readonly List<TraitEntry> _entries = new();
    private bool _expanded = true;

    public TraitCategory(string categoryId, TraitCategoryPrototype? prototype, IEnumerable<TraitPrototype> traits)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CategoryId = categoryId;
        Prototype = prototype;
        CategoryNameLabel.Text = prototype == null
            ? _loc.GetString("humanoid-profile-editor-traits-default-category")
            : _loc.GetString(prototype.Name);

        HeaderButton.OnPressed += _ => SetExpanded(!_expanded);

        foreach (var trait in traits)
        {
            var entry = new TraitEntry(trait);
            _entries.Add(entry);
            TraitsContainer.AddChild(entry);
        }

        SetExpanded(true);
        UpdateStats(0, 0);
    }

    public void SetExpanded(bool expanded)
    {
        _expanded = expanded;
        TraitsContainer.Visible = expanded;
        ExpandIcon.Text = expanded ? "▾" : "▸";
        InvalidateMeasure();
        InvalidateArrange();
    }

    public void UpdateStats(int selected, int points, int? maxPoints = null)
    {
        if (maxPoints is >= 0)
        {
            CategoryStatsLabel.Text = _loc.GetString("trait-editor-category-stats",
                ("selected", selected), ("points", points), ("max", maxPoints.Value));
            return;
        }

        CategoryStatsLabel.Text = _loc.GetString("trait-editor-category-selected",
            ("selected", selected));
    }
}
