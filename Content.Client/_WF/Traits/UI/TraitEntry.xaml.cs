using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.Traits.UI;

[GenerateTypedNameReferences]
public sealed partial class TraitEntry : PanelContainer
{
    [Dependency] private ILocalizationManager _loc = default!;

    public TraitPrototype Trait { get; }

    /// <summary>Whether the entry is shown before the search filter is applied.</summary>
    public bool Available { get; set; } = true;

    public event Action<TraitEntry, bool>? Toggled;

    private bool _updating;

    public TraitEntry(TraitPrototype trait)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Trait = trait;
        TraitNameLabel.Text = _loc.GetString(trait.Name);

        if (trait.Description is { } description)
            TraitDescriptionLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(_loc.GetString(description)));
        else
            TraitDescriptionLabel.Visible = false;

        var cost = trait.Cost;
        TraitCostLabel.Text = cost switch
        {
            > 0 => $"-{cost}",
            < 0 => $"+{-cost}",
            _ => "0",
        };
        TraitCostLabel.ModulateSelfOverride = cost switch
        {
            > 0 => Color.Red,
            < 0 => Color.Green,
            _ => Color.Gray,
        };

        TraitCheckbox.OnToggled += args =>
        {
            if (_updating)
                return;

            Toggled?.Invoke(this, args.Pressed);
        };
    }

    public void SetSelected(bool selected)
    {
        _updating = true;
        TraitCheckbox.Pressed = selected;
        _updating = false;
    }

    public void SetDisabled(bool disabled)
    {
        TraitCheckbox.Disabled = disabled;
        ModulateSelfOverride = disabled ? Color.FromHex("#888888") : null;
    }

    public void SetTooltip(string? text)
    {
        if (string.IsNullOrEmpty(text))
        {
            TooltipSupplier = null;
            return;
        }

        TooltipSupplier = _ =>
        {
            var tooltip = new Tooltip();
            tooltip.SetMessage(FormattedMessage.FromMarkupPermissive(text));
            return tooltip;
        };
    }
}
