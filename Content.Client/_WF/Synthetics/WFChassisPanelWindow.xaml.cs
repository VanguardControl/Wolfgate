/// <summary>
/// The chassis panel: a diagnostics terminal for a synthetic body's own parts and components, with the controls for
/// them. Rows are updated in place while the entry counts stay the same.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFChassisPanelWindow : FancyWindow
{
    /// <summary>Seconds a second click has to land within to confirm a dangerous control.</summary>
    public const float ConfirmSeconds = 3f;

    private const string ChargeBand = "wf-chassis-band-charge";
    private const int GaugeWidth = 8;

    private const float NameWidth = 110;
    private const float StateWidth = 92;
    private const float GaugeColumn = 150;
    private const float LoadWidth = 64;
    private const float ButtonWidth = 86;
    private const float SlotWidth = 150;
    private const float BandWidth = 96;
    private const float VitalWidth = 62;
    private const float DisconnectWidth = 118;

    private IGameTiming _timing = default!;
    private ILocalizationManager _loc = default!;

    private readonly List<PartRow> _partRows = new();
    private readonly List<OrganRow> _organRows = new();
    private WFChassisPanelState? _state;
    private ArmKey? _armed;
    private TimeSpan _armedUntil;

    /// <summary>Raised with the part and whether to isolate (true) or restore it.</summary>
    public event Action<NetEntity, bool>? OnIsolate;

    public event Action<NetEntity>? OnDetach;
    public event Action<NetEntity>? OnDisconnect;
    public event Action? OnToggleBay;
    public event Action? OnReboot;
    public event Action<bool>? OnOverclock;

    /// <summary>The part rows, in the order the state listed them.</summary>
    public IReadOnlyList<PartRow> Parts => _partRows;

    /// <summary>The component rows, in the order the state listed them.</summary>
    public IReadOnlyList<OrganRow> Organs => _organRows;

    public BaseButton BayButton => OpenBayButton;
    public BaseButton RebootControl => RebootButton;
    public BaseButton OverclockControl => OverclockButton;

    public WFChassisPanelWindow()
    {
        RobustXamlLoader.Load(this);
        _timing = IoCManager.Resolve<IGameTiming>();
        _loc = IoCManager.Resolve<ILocalizationManager>();

        Backdrop.PanelOverride = Box(Screen, margin: 8f);
        HeaderPanel.PanelOverride = Box(Panel, Border, 8f);
        ControlsPanel.PanelOverride = Box(Panel, Border, 6f);

        Style(PanelTitle, 16, Amber, true);
        Style(StatusLabel, 11, Alert, true);
        foreach (var label in new[] { PowerLabel, FluidLabel, SensorLabel, CoreLabel })
            Style(label, 11, Amber);

        PartsHost.AddChild(Heading(Loc.GetString("wf-chassis-ui-parts")));
        PartsHost.AddChild(Header(new[]
        {
            (Loc.GetString("wf-chassis-ui-col-part"), NameWidth),
            (Loc.GetString("wf-chassis-ui-col-state"), StateWidth),
            (Loc.GetString("wf-chassis-ui-col-integrity"), GaugeColumn),
            (Loc.GetString("wf-chassis-ui-col-load"), LoadWidth),
            (Loc.GetString("wf-chassis-ui-col-faults"), 0f),
        }, ButtonWidth * 2 + 8));

        OrgansHost.AddChild(Heading(Loc.GetString("wf-chassis-ui-components")));
        OrgansHost.AddChild(Header(new[]
        {
            (Loc.GetString("wf-chassis-ui-col-slot"), SlotWidth),
            (Loc.GetString("wf-chassis-ui-col-component"), 0f),
            (Loc.GetString("wf-chassis-ui-col-health"), GaugeColumn),
            (Loc.GetString("wf-chassis-ui-col-band"), BandWidth),
            (string.Empty, VitalWidth),
        }, DisconnectWidth));

        var controlsHeading = Heading(Loc.GetString("wf-chassis-ui-controls"));
        ControlsHost.AddChild(controlsHeading);
        controlsHeading.SetPositionFirst();

        foreach (var button in new[] { OpenBayButton, RebootButton, OverclockButton })
            StyleButton(button);

        OpenBayButton.OnPressed += _ => OnToggleBay?.Invoke();
        RebootButton.OnPressed += _ =>
        {
            if (Confirm(new ArmKey("reboot", null)))
                OnReboot?.Invoke();
        };
        OverclockButton.OnToggled += args => OnOverclock?.Invoke(args.Pressed);

        Update(new WFChassisPanelState());
    }

    /// <summary>Show a new state; rows are rebuilt only when the number of entries changed.</summary>
    public void Update(WFChassisPanelState state)
    {
        _state = state;

        StatusLabel.Text = state.Status.Length > 0 ? Loc.GetString(state.Status) : string.Empty;
        StatusLabel.Visible = state.Status.Length > 0;

        SetGauge(PowerLabel, "wolfmed-synthetic-row-power", state.Power, state.Power >= 0f);
        SetGauge(FluidLabel, "wolfmed-synthetic-row-fluid", state.Fluid, true);
        SetGauge(SensorLabel, "wolfmed-synthetic-row-sensor", state.Sensors, true);

        CoreLabel.Visible = state.CoreTemperature >= 0f;
        CoreLabel.Text = Loc.GetString("wolfmed-synthetic-row-core") + " " + Loc.GetString("wolfmed-synthetic-row-core-temp",
            ("value", (int) MathF.Round(state.CoreTemperature)));

        SyncParts(state.Parts);
        SyncOrgans(state.Organs);

        OpenBayButton.Text = Loc.GetString(state.BayOpen ? "wf-chassis-ui-bay-close" : "wf-chassis-ui-bay-open");
        OpenBayButton.Label.FontColorOverride = state.BayOpen ? Alert : Amber;
        RebootButton.Text = Loc.GetString(IsArmed(new ArmKey("reboot", null)) ? "wf-chassis-ui-confirm" : "wf-chassis-ui-reboot");
        RebootButton.Label.FontColorOverride = IsArmed(new ArmKey("reboot", null)) ? Alert : Amber;
        OverclockButton.Pressed = state.Overclocked;
        OverclockButton.Text = Loc.GetString(state.Overclocked ? "wf-chassis-ui-overclock-on" : "wf-chassis-ui-overclock-off");
        OverclockButton.Label.FontColorOverride = state.Overclocked ? Alert : Amber;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_armed == null || _timing.RealTime < _armedUntil)
            return;

        _armed = null;
        if (_state != null)
            Update(_state);
    }

    private void SyncParts(List<WFChassisPartEntry> entries)
    {
        if (_partRows.Count != entries.Count)
        {
            foreach (var row in _partRows)
                PartsHost.RemoveChild(row.Root);
            _partRows.Clear();
            for (var i = 0; i < entries.Count; i++)
            {
                var row = new PartRow();
                row.Isolate.OnPressed += _ => PressIsolate(row);
                row.Detach.OnPressed += _ => PressDetach(row);
                _partRows.Add(row);
                PartsHost.AddChild(row.Root);
            }
        }

        for (var i = 0; i < entries.Count; i++)
            ApplyPart(_partRows[i], entries[i]);
    }

    private void SyncOrgans(List<WFChassisOrganEntry> entries)
    {
        if (_organRows.Count != entries.Count)
        {
            foreach (var row in _organRows)
                OrgansHost.RemoveChild(row.Root);
            _organRows.Clear();
            for (var i = 0; i < entries.Count; i++)
            {
                var row = new OrganRow();
                row.Disconnect.OnPressed += _ => PressDisconnect(row);
                _organRows.Add(row);
                OrgansHost.AddChild(row.Root);
            }
        }

        for (var i = 0; i < entries.Count; i++)
            ApplyOrgan(_organRows[i], entries[i]);
    }

    private static void ApplyPart(PartRow row, WFChassisPartEntry entry)
    {
        row.Entry = entry;
        row.Name.Text = Loc.GetString(entry.Name);

        var (stateKey, stateColour) = entry switch
        {
            { Attached: false } => ("wf-chassis-ui-state-detached", Alert),
            { Isolated: true } => ("wf-chassis-ui-state-isolated", Cyan),
            { Loose: true } => ("wf-chassis-ui-state-loose", Amber),
            { Working: false } => ("wf-chassis-ui-state-offline", Alert),
            _ => ("wf-chassis-ui-state-ok", Good),
        };
        row.State.Text = Loc.GetString(stateKey);
        row.State.FontColorOverride = stateColour;

        if (entry.Attached)
        {
            row.Integrity.Text = GaugeText(entry.Integrity);
            row.Integrity.FontColorOverride = FractionColour(entry.Integrity);
            row.Load.Text = Percent(entry.Pain);
            row.Load.FontColorOverride = entry.Pain >= 0.5f ? Alert : AmberDim;
        }
        else
        {
            row.Integrity.Text = row.Load.Text = Loc.GetString("wf-chassis-ui-none");
            row.Integrity.FontColorOverride = row.Load.FontColorOverride = AmberDim;
        }

        row.Faults.Text = entry.Faults.Count == 0
            ? Loc.GetString("wf-chassis-ui-none")
            : string.Join(", ", entry.Faults.Select(fault => Loc.GetString(fault)));
        row.Faults.FontColorOverride = entry.Faults.Count == 0 ? AmberDim : Amber;

        row.Isolate.Text = Loc.GetString(entry.Isolated ? "wf-chassis-ui-restore" : "wf-chassis-ui-isolate");
        SetEnabled(row.Isolate, entry.Part != null && entry.Attached && IsLimb(entry.Slot));

        row.Detach.Text = Loc.GetString("wf-chassis-ui-detach");
        SetEnabled(row.Detach, entry.Part != null && entry.CanDetach);
    }

    private void ApplyOrgan(OrganRow row, WFChassisOrganEntry entry)
    {
        row.Entry = entry;
        row.Slot.Text = _loc.TryGetString($"wf-chassis-slot-{entry.Slot}", out var slot) ? slot : entry.Slot;

        var present = entry.Organ != null;
        row.Name.Text = present ? entry.Name.ToUpperInvariant() : Loc.GetString("wf-chassis-ui-empty");
        row.Name.FontColorOverride = present ? Amber : AmberDim;

        var hasGauge = present && entry.Health >= 0f;
        var charge = entry.Band == ChargeBand;
        row.Health.Text = hasGauge ? GaugeText(entry.Health) : Loc.GetString("wf-chassis-ui-none");
        row.Health.FontColorOverride = hasGauge ? (charge ? Cyan : FractionColour(entry.Health)) : AmberDim;

        row.Band.Text = present && entry.Band.Length > 0 ? Loc.GetString(entry.Band) : string.Empty;
        row.Band.FontColorOverride = hasGauge && !charge && entry.Health < 0.25f ? Alert : AmberDim;

        row.Vital.Text = entry.Vital ? Loc.GetString("wf-chassis-ui-vital") : string.Empty;

        var armed = entry.Organ is { } organ && IsArmed(new ArmKey("organ", organ));
        row.Disconnect.Text = Loc.GetString(armed ? "wf-chassis-ui-confirm" : "wf-chassis-ui-disconnect");
        SetEnabled(row.Disconnect, present && entry.CanDisconnect);
        if (armed)
            row.Disconnect.Label.FontColorOverride = Alert;
    }

    private void PressIsolate(PartRow row)
    {
        if (row.Entry is { Part: { } part } entry)
            OnIsolate?.Invoke(part, !entry.Isolated);
    }

    private void PressDetach(PartRow row)
    {
        if (row.Entry is { Part: { } part })
            OnDetach?.Invoke(part);
    }

    private void PressDisconnect(OrganRow row)
    {
        if (row.Entry is not { Organ: { } organ } entry)
            return;

        if (entry.Vital && !Confirm(new ArmKey("organ", organ)))
            return;

        OnDisconnect?.Invoke(organ);
    }

    private bool IsArmed(ArmKey key) => _armed == key && _timing.RealTime < _armedUntil;

    /// <summary>Arms the control on the first click; true on a second click on the same control inside the window.</summary>
    private bool Confirm(ArmKey key)
    {
        var confirmed = IsArmed(key);
        if (confirmed)
        {
            _armed = null;
        }
        else
        {
            _armed = key;
            _armedUntil = _timing.RealTime + TimeSpan.FromSeconds(ConfirmSeconds);
        }

        if (_state != null)
            Update(_state);
        return confirmed;
    }

    /// <summary>A limb the panel may isolate: arms, hands, legs and feet. Never the head, torso or frame.</summary>
    public static bool IsLimb(TargetBodyPart slot) =>
        (slot & (TargetBodyPart.Arms | TargetBodyPart.Hands | TargetBodyPart.Legs | TargetBodyPart.Feet)) != 0 &&
        (slot & (TargetBodyPart.Head | TargetBodyPart.Torso | TargetBodyPart.Groin)) == 0;

    private static void SetGauge(Label label, string key, float fraction, bool visible)
    {
        label.Visible = visible;
        if (!visible)
            return;

        label.Text = Loc.GetString(key) + " " + GaugeText(fraction);
        label.FontColorOverride = FractionColour(fraction);
    }

    private static string GaugeText(float fraction) => $"{Gauge(fraction, GaugeWidth)} {Percent(fraction),4}";

    private static string Percent(float fraction) => $"{(int) MathF.Round(Math.Clamp(fraction, 0f, 1f) * 100f)}%";

    private static Color FractionColour(float fraction) => fraction >= 0.5f ? Good : fraction >= 0.25f ? Amber : Alert;

    private static void Style(Label label, int size, Color colour, bool bold = false)
    {
        label.FontOverride = AutodocStyle.Mono(size, bold);
        label.FontColorOverride = colour;
    }

    private static void StyleButton(Button button)
    {
        button.StyleBoxOverride = Box(Panel, Border, 4f);
        button.Label.FontOverride = AutodocStyle.Mono(11, true);
        button.Label.FontColorOverride = Amber;
    }

    private static void SetEnabled(Button button, bool enabled)
    {
        button.Disabled = !enabled;
        button.Label.FontColorOverride = enabled ? Amber : AmberFaint;
    }

    private static Label Cell(float width, Color? colour = null, bool bold = false)
    {
        var label = Text(string.Empty, 11, colour ?? Amber, bold);
        if (width > 0)
            label.SetWidth = width;
        else
            label.HorizontalExpand = true;
        label.ClipText = true;
        return label;
    }

    private static BoxContainer Row()
    {
        return new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
    }

    /// <summary>The column titles, one label per column (width 0 takes the remaining space), and a spacer over the buttons.</summary>
    private static Control Header(IEnumerable<(string Text, float Width)> columns, float buttons)
    {
        var row = Row();
        foreach (var (text, width) in columns)
        {
            var label = Cell(width, AmberDim, true);
            label.Text = text;
            row.AddChild(label);
        }

        row.AddChild(new Control { SetWidth = buttons });
        return row;
    }

    /// <summary>One part row's controls.</summary>
    public sealed class PartRow
    {
        public readonly BoxContainer Root = Row();
        public readonly Label Name = Cell(NameWidth, bold: true);
        public readonly Label State = Cell(StateWidth, bold: true);
        public readonly Label Integrity = Cell(GaugeColumn);
        public readonly Label Load = Cell(LoadWidth);
        public readonly Label Faults = Cell(0);
        public readonly Button Isolate = FlatButton(string.Empty);
        public readonly Button Detach = FlatButton(string.Empty);

        /// <summary>The entry this row currently shows.</summary>
        public WFChassisPartEntry? Entry;

        public PartRow()
        {
            Isolate.SetWidth = Detach.SetWidth = ButtonWidth;
            Root.AddChild(Name);
            Root.AddChild(State);
            Root.AddChild(Integrity);
            Root.AddChild(Load);
            Root.AddChild(Faults);
            Root.AddChild(Isolate);
            Root.AddChild(Detach);
        }
    }

    /// <summary>One component row's controls.</summary>
    public sealed class OrganRow
    {
        public readonly BoxContainer Root = Row();
        public readonly Label Slot = Cell(SlotWidth, AmberDim, true);
        public readonly Label Name = Cell(0);
        public readonly Label Health = Cell(GaugeColumn);
        public readonly Label Band = Cell(BandWidth);
        public readonly Label Vital = Cell(VitalWidth, Alert, true);
        public readonly Button Disconnect = FlatButton(string.Empty);

        /// <summary>The entry this row currently shows.</summary>
        public WFChassisOrganEntry? Entry;

        public OrganRow()
        {
            Disconnect.SetWidth = DisconnectWidth;
            Root.AddChild(Slot);
            Root.AddChild(Name);
            Root.AddChild(Health);
            Root.AddChild(Band);
            Root.AddChild(Vital);
            Root.AddChild(Disconnect);
        }
    }

    private readonly record struct ArmKey(string Kind, NetEntity? Id);
}
