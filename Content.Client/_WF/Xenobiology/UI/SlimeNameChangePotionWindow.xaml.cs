using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Xenobiology.Potions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Xenobiology.UI;

/// <summary>
/// A text box for the name a name change potion gives.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SlimeNameChangePotionWindow : FancyWindow
{
    public event Action<string>? OnNameChanged;

    private string _initialName = string.Empty;

    public SlimeNameChangePotionWindow()
    {
        RobustXamlLoader.Load(this);

        NameLineEdit.IsValid = text => text.Length <= SlimeIdentityPotionSystem.MaxNameLength;
        NameLineEdit.OnTextChanged += args =>
        {
            OnNameChanged?.Invoke(args.Text);
            UpdateButtons();
        };
        ResetButton.OnPressed += _ => NameLineEdit.SetText(_initialName, true);
        ClearButton.OnPressed += _ => NameLineEdit.SetText(string.Empty, true);
    }

    protected override void Opened()
    {
        base.Opened();
        NameLineEdit.GrabKeyboardFocus();
    }

    /// <summary>
    /// Fills the box with the potion's stored name.
    /// </summary>
    public void SetName(string name)
    {
        _initialName = name;
        NameLineEdit.Text = name;
        NameLineEdit.CursorPosition = name.Length;
        UpdateButtons();
    }

    private void UpdateButtons()
    {
        ResetButton.Disabled = NameLineEdit.Text == _initialName;
        ClearButton.Disabled = NameLineEdit.Text.Length == 0;
    }
}
