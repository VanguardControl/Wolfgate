using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Blueprints;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._WF.Blueprints;

/// <summary>The locator's window: the pattern list, the hunt request and the running hunt.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFBlueprintLocatorWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action<List<string>>? OnLocate;
    public event Action? OnAbandon;

    private readonly HashSet<string> _selected = new();
    private WFBlueprintLocatorState? _state;

    public WFBlueprintLocatorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        LocateButton.OnPressed += _ => OnLocate?.Invoke(_selected.ToList());
        AbandonButton.OnPressed += _ => OnAbandon?.Invoke();
    }

    public void UpdateState(WFBlueprintLocatorState state)
    {
        _state = state;
        _selected.RemoveWhere(id => state.Patterns.All(p => p.Id != id || p.Owned));
        Rebuild();
    }

    private int? SelectedTier()
    {
        foreach (var id in _selected)
        {
            if (_proto.TryIndex<WFBlueprintPatternPrototype>(id, out var pattern))
                return pattern.Tier;
        }

        return null;
    }

    private void Rebuild()
    {
        if (_state is not { } state)
            return;

        var cooling = _timing.CurTime < state.NextHunt;
        StatusLabel.Text = !state.Linked
            ? Loc.GetString("wf-blueprint-locator-status-unlinked")
            : cooling
                ? Loc.GetString("wf-blueprint-locator-status-cooldown", ("minutes", Math.Ceiling((state.NextHunt - _timing.CurTime).TotalMinutes)))
                : Loc.GetString("wf-blueprint-locator-status-ready");

        if (state.Hunt is { } hunt)
        {
            var names = string.Join(", ", hunt.Patterns.Select(PatternName));
            HuntLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("wf-blueprint-locator-hunt",
                ("site", hunt.Site), ("world", hunt.World), ("tier", hunt.Tier), ("patterns", names), ("remaining", hunt.Remaining))));
            AbandonButton.Disabled = false;
        }
        else
        {
            HuntLabel.SetMessage(Loc.GetString("wf-blueprint-locator-no-hunt"));
            AbandonButton.Disabled = true;
        }

        var tier = SelectedTier();
        PatternList.RemoveAllChildren();
        int? lastTier = null;
        foreach (var entry in state.Patterns)
        {
            if (!_proto.TryIndex<WFBlueprintPatternPrototype>(entry.Id, out var pattern))
                continue;

            if (lastTier != pattern.Tier)
            {
                lastTier = pattern.Tier;
                PatternList.AddChild(new Label
                {
                    Text = Loc.GetString("wf-blueprint-tier", ("tier", pattern.Tier)),
                    StyleClasses = { "LabelKeyText" },
                    Margin = new Thickness(0, 6, 0, 2),
                });
            }

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var icon = new EntityPrototypeView { SetSize = new System.Numerics.Vector2(32, 32) };
            icon.SetPrototype(pattern.Icon);
            row.AddChild(icon);

            var selected = _selected.Contains(entry.Id);
            var box = new CheckBox
            {
                Text = entry.Owned
                    ? Loc.GetString("wf-blueprint-pattern-owned", ("name", Loc.GetString(pattern.Name)))
                    : Loc.GetString(pattern.Name),
                Pressed = selected,
                Disabled = entry.Owned || state.Hunt != null
                    || !selected && _selected.Count >= state.MaxPatterns && tier == pattern.Tier,
                ToolTip = Loc.GetString(pattern.Description),
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };

            var id = entry.Id;
            var patternTier = pattern.Tier;
            box.OnToggled += args =>
            {
                if (args.Pressed)
                {
                    // One tier a hunt: picking another tier starts the selection over.
                    if (SelectedTier() is { } current && current != patternTier)
                        _selected.Clear();
                    _selected.Add(id);
                }
                else
                {
                    _selected.Remove(id);
                }

                Rebuild();
            };

            row.AddChild(box);
            PatternList.AddChild(row);
        }

        tier = SelectedTier();
        FeeLabel.Text = tier is { } t && state.Fees.Length > 0
            ? Loc.GetString("wf-blueprint-locator-fee", ("fee", state.Fees[Math.Clamp(t - 1, 0, state.Fees.Length - 1)]),
                ("count", _selected.Count), ("max", state.MaxPatterns))
            : Loc.GetString("wf-blueprint-locator-pick", ("max", state.MaxPatterns));
        LocateButton.Disabled = !state.Linked || cooling || state.Hunt != null || _selected.Count == 0;
    }

    private string PatternName(string id)
    {
        return _proto.TryIndex<WFBlueprintPatternPrototype>(id, out var pattern) ? Loc.GetString(pattern.Name) : id;
    }
}
