using Content.Client.UserInterface.Controls;
using Content.Shared._WF.MappingTools;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.MappingTools;

/// <summary>
/// Lists map files with a preview of the selected one, and saves and opens them through the server.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MappingMapsWindow : FancyWindow
{
    private List<MappingMapFile> _files = new();
    private string? _selected;

    /// <summary>
    /// The save waiting for a second click because it would overwrite a file.
    /// </summary>
    private bool? _confirmWholeMap;

    public event Action? RefreshRequested;
    public event Action<string>? PreviewRequested;
    public event Action<string, bool>? LoadRequested;
    public event Action<string, bool>? SaveRequested;

    public MappingMapsWindow()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += _ => Populate();
        RefreshButton.OnPressed += _ => RefreshRequested?.Invoke();
        FileList.OnItemSelected += args => Select(FileList[args.ItemIndex].Metadata as string);
        OpenButton.OnPressed += _ => Load(false);
        LoadHereButton.OnPressed += _ => Load(true);
        SaveGridButton.OnPressed += _ => Save(false);
        SaveMapButton.OnPressed += _ => Save(true);
        NameEdit.OnTextChanged += _ => ResetConfirm();
        Preview.PreviewUpdated += UpdateInfo;

        Preview.ShowMessage("wf-mapping-maps-preview-none");
    }

    public void SetFiles(List<MappingMapFile> files, string saveFolder)
    {
        _files = files;
        SaveFolderLabel.Text = Loc.GetString("wf-mapping-maps-save-folder", ("folder", saveFolder));
        Populate();
    }

    public void SetPreview(MappingMapsPreviewEvent ev)
    {
        if (ev.Path != _selected)
            return;

        if (ev.Yaml == null)
        {
            Preview.ShowMessage(ev.Error ?? "wf-ship-preview-failed");
            return;
        }

        // Whole maps hold several grids and don't fit the grid previewer, and can't be dropped in as one grid.
        if (ev.Yaml.Contains("category: Map"))
        {
            Preview.ShowMessage("wf-mapping-maps-preview-whole-map");
            return;
        }

        LoadHereButton.Disabled = false;
        Preview.SetGridText(ev.Path, ev.Yaml, null);
    }

    private void Populate()
    {
        FileList.Clear();
        var filter = SearchBar.Text.Trim();

        foreach (var source in Enum.GetValues<MappingMapSource>())
        {
            var header = false;
            foreach (var file in _files)
            {
                if (file.Source != source ||
                    filter.Length > 0 && !file.Path.Contains(filter, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                if (!header)
                {
                    FileList.AddItem(Loc.GetString($"wf-mapping-maps-source-{source.ToString().ToLowerInvariant()}"),
                        selectable: false).Disabled = true;
                    header = true;
                }

                var item = FileList.AddItem("  " + file.Path, metadata: file.Path);
                item.Selected = file.Path == _selected;
            }
        }
    }

    private void Select(string? path)
    {
        if (path == null || path == _selected)
            return;

        _selected = path;
        OpenButton.Disabled = false;
        LoadHereButton.Disabled = true;
        PreviewInfo.Text = path;
        Preview.ShowMessage("wf-ship-preview-loading");
        PreviewRequested?.Invoke(path);
    }

    private void UpdateInfo()
    {
        if (_selected == null)
            return;

        PreviewInfo.Text = Preview.HasPreview
            ? Loc.GetString("wf-mapping-maps-info", ("path", _selected), ("width", Preview.GridSize.X),
                ("height", Preview.GridSize.Y), ("tiles", Preview.TileCount))
            : _selected;
    }

    private void Load(bool here)
    {
        if (_selected != null)
            LoadRequested?.Invoke(_selected, here);
    }

    private void Save(bool wholeMap)
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            return;

        // Saving over an existing file takes a second click.
        var path = $"{MappingMaps.SaveFolder}/{name}.yml";
        if (_confirmWholeMap != wholeMap && _files.Exists(f => f.Path == path))
        {
            ResetConfirm();
            _confirmWholeMap = wholeMap;
            (wholeMap ? SaveMapButton : SaveGridButton).Text = Loc.GetString("wf-mapping-maps-overwrite");
            return;
        }

        ResetConfirm();
        SaveRequested?.Invoke(name, wholeMap);
    }

    private void ResetConfirm()
    {
        _confirmWholeMap = null;
        SaveGridButton.Text = Loc.GetString("wf-mapping-maps-save-grid");
        SaveMapButton.Text = Loc.GetString("wf-mapping-maps-save-map");
    }

    public override void Close()
    {
        base.Close();
        Preview.Release();
    }
}
