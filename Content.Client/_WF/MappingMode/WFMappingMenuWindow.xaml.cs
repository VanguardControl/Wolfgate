using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.MappingMode;
using Content.Shared._WF.MappingTools;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Timing;

namespace Content.Client._WF.MappingMode;

/// <summary>
/// The in-game Mapping window: Session, Save and Library tabs. <see cref="WFMappingMenuUIController"/> wires it up.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingMenuWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Color SuccessColor = Color.FromHex("#7fd17f");
    private static readonly Color FailureColor = Color.FromHex("#ff7a7a");

    private WFMappingSessionInfo? _session;
    private int? _namedSession;
    private List<MappingMapFile> _referenceFiles = new();
    private string? _selectedReference;

    public event Action<NetUserId>? KickRequested;
    public event Action<int>? AutosaveRequested;
    public event Action<string>? ReferencePicked;

    public WFMappingMenuWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("wf-mapping-mode-menu-tab-session"));
        Tabs.SetTabTitle(1, Loc.GetString("wf-mapping-mode-menu-tab-save"));
        Tabs.SetTabTitle(2, Loc.GetString("wf-mapping-mode-menu-tab-library"));

        foreach (var minutes in WFMappingAutosaveSteps.Minutes)
        {
            AutosaveOption.AddItem(minutes == 0
                ? Loc.GetString("wf-mapping-mode-menu-autosave-off")
                : Loc.GetString("wf-mapping-mode-menu-autosave-step", ("minutes", minutes)), minutes);
        }

        AutosaveOption.OnItemSelected += args =>
        {
            if (_session == null || args.Id == _session.AutosaveMinutes)
                return;

            AutosaveOption.SelectId(args.Id);
            AutosaveRequested?.Invoke(args.Id);
        };

        LibraryList.ShowOpen = false;
        ReferenceButton.OnToggled += args => ReferenceBox.Visible = args.Pressed;
        ReferenceSearch.OnTextChanged += _ => PopulateReferences();
        ReferenceList.OnItemSelected += args => SelectReference(ReferenceList[args.ItemIndex].Metadata as string);
        ReferenceList.OnItemDeselected += _ => SelectReference(null);
        ReferencePlaceButton.OnPressed += _ =>
        {
            if (_selectedReference != null)
                ReferencePicked?.Invoke(_selectedReference);
        };
    }

    /// <summary>Shows the session, or the admin's Return to lobby when there is none.</summary>
    public void SetSession(WFMappingSessionInfo? session, NetUserId? self, bool admin)
    {
        _session = session;
        NoSessionBox.Visible = session == null;
        ReturnButton.Visible = session == null && admin;
        SessionBox.Visible = session != null;

        if (session == null)
        {
            UpdateSaveTimes();
            return;
        }

        var owner = self == session.Owner;
        SessionNameLabel.Text = session.Name;
        CodeLabel.Text = Loc.GetString("wf-mapping-mode-menu-code", ("code", session.Code));

        var limits = session.Limits;
        StatusLabel.Text = Loc.GetString("wf-mapping-mode-menu-status",
            ("grids", limits.Grids),
            ("maxGrids", limits.MaxGrids),
            ("entities", limits.Entities.ToString("N0", CultureInfo.InvariantCulture)),
            ("maxEntities", limits.MaxEntities.ToString("N0", CultureInfo.InvariantCulture)),
            ("size", limits.MapSize));

        MemberList.RemoveAllChildren();
        foreach (var member in session.Members)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new Label
            {
                Text = Loc.GetString("wf-mapping-mode-menu-member", ("name", member.Name),
                    ("owner", member.User == session.Owner ? "yes" : "no"),
                    ("away", member.Present ? "no" : "yes")),
                HorizontalExpand = true,
                ClipText = true,
            });

            if (owner && member.User != session.Owner)
            {
                var user = member.User;
                var kick = new ConfirmButton { Text = Loc.GetString("wf-mapping-mode-menu-kick") };
                kick.OnPressed += _ => KickRequested?.Invoke(user);
                row.AddChild(kick);
            }

            MemberList.AddChild(row);
        }

        AutosaveOption.SelectId(session.AutosaveMinutes);
        AutosaveOption.Disabled = !owner;
        AutosaveHint.Text = owner ? string.Empty : Loc.GetString("wf-mapping-mode-menu-autosave-owner-only");

        if (_namedSession != session.Id)
        {
            _namedSession = session.Id;
            SaveNameEdit.Text = session.Name;
        }

        SaveNameEdit.PlaceHolder = session.Name;
        DirtyLabel.Text = Loc.GetString(session.Dirty ? "wf-mapping-mode-menu-dirty" : "wf-mapping-mode-menu-clean");
        UpdateSaveTimes();
    }

    public void SetLibrary(WFMappingLibraryEvent? library)
    {
        LibraryList.SetLibrary(library);
        LibraryUsage.Text = library == null
            ? string.Empty
            : Loc.GetString("wf-mapping-mode-library-usage",
                ("maps", library.Maps.Count),
                ("maxMaps", library.MaxMaps),
                ("used", WFMappingLibraryList.FormatMiB(library.Bytes)),
                ("max", WFMappingLibraryList.FormatMiB(library.MaxBytes)));
    }

    public void SetReferenceFiles(List<MappingMapFile> files)
    {
        _referenceFiles = files;
        PopulateReferences();
    }

    public void SetResult(WFMappingResult? result)
    {
        ShowResult(ResultLabel, result);
    }

    /// <summary>Shows an outcome on a label, green or red.</summary>
    public static void ShowResult(Label label, WFMappingResult? result)
    {
        label.Text = result?.Text ?? string.Empty;
        label.FontColorOverride = result is { Success: false } ? FailureColor : SuccessColor;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateSaveTimes();
    }

    private void UpdateSaveTimes()
    {
        if (_session == null)
        {
            LastSavedLabel.Text = string.Empty;
            NextAutosaveLabel.Text = string.Empty;
            DirtyLabel.Text = string.Empty;
            return;
        }

        LastSavedLabel.Text = _session.LastSaved is { } saved
            ? Loc.GetString("wf-mapping-mode-menu-last-saved", ("time", WFMappingLibraryList.FormatStamp(saved)))
            : Loc.GetString("wf-mapping-mode-menu-never-saved");

        if (_session.NextAutosave is not { } next)
        {
            NextAutosaveLabel.Text = Loc.GetString("wf-mapping-mode-menu-autosave-disabled");
            return;
        }

        var left = next - _timing.CurTime;
        if (left < TimeSpan.Zero)
            left = TimeSpan.Zero;

        NextAutosaveLabel.Text = Loc.GetString("wf-mapping-mode-menu-next-autosave",
            ("time", left.ToString(@"m\:ss", CultureInfo.InvariantCulture)));
    }

    private void PopulateReferences()
    {
        ReferenceList.Clear();
        var filter = ReferenceSearch.Text.Trim();

        foreach (var source in Enum.GetValues<MappingMapSource>())
        {
            var header = false;
            foreach (var file in _referenceFiles)
            {
                var shown = ShortPath(file);
                if (file.Source != source ||
                    filter.Length > 0 && !shown.Contains(filter, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                if (!header)
                {
                    ReferenceList.AddItem(Loc.GetString(
                            $"wf-mapping-mode-menu-reference-source-{source.ToString().ToLowerInvariant()}"),
                        selectable: false).Disabled = true;
                    header = true;
                }

                var item = ReferenceList.AddItem("  " + shown, metadata: file.Path);
                item.Selected = file.Path == _selectedReference;
            }
        }

        ReferencePlaceButton.Disabled = _selectedReference == null;
    }

    /// <summary>Library files drop the <c>/Mapping/Library/&lt;user&gt;/</c> prefix.</summary>
    private static string ShortPath(MappingMapFile file)
    {
        var path = file.Path;
        if (file.Source != MappingMapSource.Saved)
            return path;

        var root = WFMappingLibraryNames.Root.ToString() + "/";
        if (!path.StartsWith(root, StringComparison.Ordinal))
            return path;

        var user = path.IndexOf('/', root.Length);
        return user < 0 ? path : path[(user + 1)..];
    }

    private void SelectReference(string? path)
    {
        _selectedReference = path;
        ReferencePlaceButton.Disabled = path == null;
    }
}
