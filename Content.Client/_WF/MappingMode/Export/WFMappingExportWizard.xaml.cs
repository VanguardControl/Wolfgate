namespace Content.Client._WF.MappingMode.Export;

/// <summary>
/// The export wizard: Check (the issues of the session, with Go to), Details (the vessel fields of a ship) and
/// Package (save a version if needed, then download the zip). <see cref="WFMappingExportUIController"/> wires it to
/// the client system.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingExportWizard : FancyWindow
{
    [Dependency] private IConfigurationManager _cfg = default!;

    private static readonly Color ErrorColor = Color.FromHex("#ff7a7a");
    private static readonly Color WarningColor = Color.FromHex("#f0c060");
    private static readonly Color NoteColor = Color.FromHex("#a0a0a0");

    private readonly Dictionary<VesselClass, CheckBox> _classBoxes = new();
    private readonly Dictionary<VesselEngine, CheckBox> _engineBoxes = new();

    private int _step = 1;
    private WFMappingExportKind _kind = WFMappingExportKind.Ship;
    private WFMappingIssuesEvent? _issues;
    private bool _checking;
    private bool _shipPossible = true;
    private bool _dirty;
    private bool _busy;

    /// <summary>The library map the wizard exports, and its version folder; null is the newest.</summary>
    public string MapName { get; private set; } = string.Empty;

    public string? Version { get; private set; }

    /// <summary>Whether the mapper is in this map's session, so checks run and a version can be saved first.</summary>
    public bool InSession { get; private set; }

    public WFMappingExportKind Kind => _kind;

    public int Step => _step;

    /// <summary>Raised to run the issues check for a scope.</summary>
    public event Action<WFMappingIssueScope>? CheckRequested;

    public event Action<WFMappingIssue>? GoToRequested;

    /// <summary>Raised with the kind and, for a ship, the details read off the form; the controller saves first if needed.</summary>
    public event Action<WFMappingExportKind, WFMappingShipDetails?>? ExportRequested;

    public WFMappingExportWizard()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ShipKindButton.OnPressed += _ => SetKind(WFMappingExportKind.Ship);
        MapKindButton.OnPressed += _ => SetKind(WFMappingExportKind.Map);
        RecheckButton.OnPressed += _ => Check();
        BackButton.OnPressed += _ => Go(-1);
        NextButton.OnPressed += _ => Go(1);
        PackageButton.OnPressed += _ => Package();

        NameEdit.OnTextChanged += _ => UpdatePreview();
        DescriptionEdit.OnTextChanged += _ => UpdateDescriptionCount();
        PriceEdit.OnTextChanged += _ => UpdatePriceHint();
        EnginesAutoCheck.OnToggled += args => SetEnginesEnabled(!args.Pressed);

        CategoryOption.AddItem(Loc.GetString("wf-mapping-export-details-auto"), (int) VesselSize.All);
        foreach (var size in new[] { VesselSize.Micro, VesselSize.Small, VesselSize.Medium, VesselSize.Large })
        {
            CategoryOption.AddItem(size.ToString(), (int) size);
        }

        CategoryOption.OnItemSelected += args => CategoryOption.SelectId(args.Id);

        foreach (var group in Enum.GetValues<ShipyardConsoleUiKey>())
        {
            GroupOption.AddItem(group.ToString(), (int) group);
        }

        GroupOption.OnItemSelected += args => GroupOption.SelectId(args.Id);

        foreach (var vesselClass in Enum.GetValues<VesselClass>())
        {
            if (vesselClass == VesselClass.All)
                continue;

            var box = new CheckBox { Text = vesselClass.ToString() };
            _classBoxes[vesselClass] = box;
            ClassGrid.AddChild(box);
        }

        foreach (var engine in Enum.GetValues<VesselEngine>())
        {
            if (engine == VesselEngine.All)
                continue;

            var box = new CheckBox { Text = engine.ToString() };
            _engineBoxes[engine] = box;
            EngineGrid.AddChild(box);
        }

    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(WFMappingModeCVars.DownloadSaveTo, OnSaveToChanged, true);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cfg.UnsubValueChanged(WFMappingModeCVars.DownloadSaveTo, OnSaveToChanged);
    }

    private void OnSaveToChanged(bool saveTo)
    {
        PackageButton.Text = Loc.GetString(saveTo
            ? "wf-mapping-export-package-button-save-to"
            : "wf-mapping-export-package-button");
    }

    /// <summary>
    /// Starts the wizard over for a map: <paramref name="shipPossible"/> is false for a version the library doesn't
    /// list as a ship, <paramref name="details"/> pre-fills the form.
    /// </summary>
    public void Open(string mapName, string? version, bool inSession, bool shipPossible, WFMappingShipDetails? details)
    {
        MapName = mapName;
        Version = version;
        InSession = inSession;
        _shipPossible = shipPossible;
        _issues = null;
        _checking = false;
        _kind = shipPossible ? WFMappingExportKind.Ship : WFMappingExportKind.Map;
        _step = 1;
        PackageStatus.Text = string.Empty;
        TargetLabel.Text = Loc.GetString("wf-mapping-export-target", ("name", mapName),
            ("version", version ?? Loc.GetString("wf-mapping-export-target-newest")));
        Fill(details ?? new WFMappingShipDetails());
        Check();
        Refresh();
    }

    public void SetSessionDirty(bool dirty)
    {
        _dirty = dirty;
        SaveFirstLabel.Visible = InSession && dirty;
    }

    /// <summary>The download's progress, and whether the client is still busy with one.</summary>
    public void SetDownload(WFMappingDownloadProgress? progress, bool busy)
    {
        _busy = busy;
        DownloadRow.SetProgress(progress is { Zip: true } ? progress : null);
        if (progress is { Zip: true, Active: false, Asking: null } && PackageStatus.Text == Loc.GetString("wf-mapping-export-package-requested"))
            SetStatus(Loc.GetString("wf-mapping-export-package-done"), true);

        PackageButton.Disabled = busy;
    }

    public void SetStatus(string text, bool ok)
    {
        WFMappingMenuWindow.ShowResult(PackageStatus, new WFMappingResult(string.Empty, text, ok));
    }

    public void SetIssues(WFMappingIssuesEvent ev)
    {
        if (ev.Scope != ScopeOf(_kind))
            return;

        _issues = ev;
        _checking = false;
        RenderIssues();
        UpdatePriceHint();
        Refresh();
    }

    /// <summary>Whether an error stands in the last ship check, which turns the ship export off.</summary>
    public bool ShipErrors => _issues is { Scope: WFMappingIssueScope.Ship } issues &&
                              issues.Issues.Exists(issue => issue.Severity == WFMappingIssueSeverity.Error);

    private static WFMappingIssueScope ScopeOf(WFMappingExportKind kind)
    {
        return kind == WFMappingExportKind.Ship ? WFMappingIssueScope.Ship : WFMappingIssueScope.Map;
    }

    private void SetKind(WFMappingExportKind kind)
    {
        if (kind == WFMappingExportKind.Ship && (!_shipPossible || ShipErrors))
            kind = WFMappingExportKind.Map;

        if (kind != _kind)
        {
            _kind = kind;
            _issues = null;
            Check();
        }

        Refresh();
    }

    private void Check()
    {
        if (!InSession)
        {
            _issues = null;
            RenderIssues();
            return;
        }

        _checking = true;
        RenderIssues();
        CheckRequested?.Invoke(ScopeOf(_kind));
    }

    private void Go(int direction)
    {
        var next = _step + direction;
        if (_kind == WFMappingExportKind.Map && next == 2)
            next += direction;

        _step = Math.Clamp(next, 1, 3);
        if (_step == 3)
            UpdatePackageSummary();

        Refresh();
    }

    private void Package()
    {
        if (_busy)
            return;

        if (_kind == WFMappingExportKind.Ship && !TryReadPrice(out _))
        {
            SetStatus(Loc.GetString("wf-mapping-export-details-price-bad", ("max", WFMappingExportLimits.MaxPrice)), false);
            return;
        }

        SetStatus(Loc.GetString(InSession && _dirty ? "wf-mapping-export-package-saving" : "wf-mapping-export-package-requested"), true);
        ExportRequested?.Invoke(_kind, _kind == WFMappingExportKind.Ship ? ReadDetails() : null);
    }

    /// <summary>Shows the current step and sets the footer and kind buttons to match.</summary>
    private void Refresh()
    {
        CheckStep.Visible = _step == 1;
        DetailsStep.Visible = _step == 2;
        PackageStep.Visible = _step == 3;
        StepLabel.Text = Loc.GetString("wf-mapping-export-step", ("step", _step), ("name", Loc.GetString(_step switch
        {
            1 => "wf-mapping-export-step-check",
            2 => "wf-mapping-export-step-details",
            _ => "wf-mapping-export-step-package",
        })));

        ShipKindButton.Pressed = _kind == WFMappingExportKind.Ship;
        MapKindButton.Pressed = _kind == WFMappingExportKind.Map;
        ShipKindButton.Disabled = !_shipPossible || ShipErrors;
        RecheckButton.Disabled = !InSession || _checking;
        BackButton.Disabled = _step == 1;
        NextButton.Visible = _step < 3;
        NextButton.Disabled = _step == 1 && _kind == WFMappingExportKind.Ship && (ShipErrors || _checking);
        DetailsForm.Visible = _kind == WFMappingExportKind.Ship;
        DetailsMapNote.Visible = _kind == WFMappingExportKind.Map;
        SaveFirstLabel.Visible = InSession && _dirty;
    }

    private void RenderIssues()
    {
        IssueList.RemoveAllChildren();
        if (!InSession)
        {
            CheckSummary.Text = string.Empty;
            IssueList.AddChild(SubLabel(Loc.GetString("wf-mapping-export-check-no-session")));
            CheckHint.SetMessage(string.Empty);
            return;
        }

        if (_checking || _issues == null)
        {
            CheckSummary.Text = Loc.GetString("wf-mapping-export-checking");
            CheckHint.SetMessage(string.Empty);
            return;
        }

        var issues = _issues.Issues;
        var summary = _issues.Summary;
        CheckSummary.Text = Loc.GetString("wf-mapping-export-check-summary",
            ("errors", issues.Count(i => i.Severity == WFMappingIssueSeverity.Error)),
            ("warnings", issues.Count(i => i.Severity == WFMappingIssueSeverity.Warning)),
            ("notes", issues.Count(i => i.Severity == WFMappingIssueSeverity.Note)),
            ("grids", summary.Grids), ("tiles", summary.Tiles), ("entities", summary.Entities),
            ("levels", summary.Levels), ("appraisal", ((int) Math.Round(summary.Appraisal)).ToString("N0", CultureInfo.InvariantCulture)));

        if (issues.Count == 0)
            IssueList.AddChild(SubLabel(Loc.GetString("wf-mapping-export-check-none")));

        foreach (var issue in issues)
        {
            IssueList.AddChild(IssueRow(issue));
        }

        CheckHint.SetMessage(Loc.GetString(_kind == WFMappingExportKind.Ship
            ? ShipErrors ? "wf-mapping-export-check-errors" : "wf-mapping-export-check-ok-ship"
            : "wf-mapping-export-check-ok-map"));
    }

    private Control IssueRow(WFMappingIssue issue)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        var (severityKey, colour) = issue.Severity switch
        {
            WFMappingIssueSeverity.Error => ("wf-mapping-export-severity-error", ErrorColor),
            WFMappingIssueSeverity.Warning => ("wf-mapping-export-severity-warning", WarningColor),
            _ => ("wf-mapping-export-severity-note", NoteColor),
        };

        row.AddChild(new Label
        {
            Text = Loc.GetString(severityKey),
            FontColorOverride = colour,
            MinWidth = 64,
            VerticalAlignment = VAlignment.Top,
        });

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        var title = new Label { Text = Loc.GetString(issue.LocKey, issue.Args()), ClipText = true };
        title.ToolTip = title.Text;
        text.AddChild(title);
        if (WFMappingIssueCatalog.TryGet(issue.RuleId, out var rule) && rule.Id != WFMappingIssueCatalog.More)
            text.AddChild(SubLabel(Loc.GetString(rule.HintKey)));

        row.AddChild(text);
        if (issue.Entity != null || issue.Where != null)
        {
            var goTo = new Button { Text = Loc.GetString("wf-mapping-export-issue-goto"), VerticalAlignment = VAlignment.Top };
            goTo.OnPressed += _ => GoToRequested?.Invoke(issue);
            row.AddChild(goTo);
        }

        return row;
    }

    private void Fill(WFMappingShipDetails details)
    {
        NameEdit.Text = details.Name;
        DescriptionEdit.TextRope = new Rope.Leaf(details.Description);
        PriceEdit.Text = details.Price > 0 ? details.Price.ToString(CultureInfo.InvariantCulture) : string.Empty;
        CategoryOption.SelectId((int) details.Category);
        GroupOption.SelectId((int) details.Group);
        foreach (var (vesselClass, box) in _classBoxes)
        {
            box.Pressed = details.Classes.Contains(vesselClass);
        }

        EnginesAutoCheck.Pressed = details.AutoEngines;
        foreach (var (engine, box) in _engineBoxes)
        {
            box.Pressed = details.Engines.Contains(engine);
        }

        SetEnginesEnabled(!details.AutoEngines);
        AccessEdit.Text = details.Access;
        RequireCrewCheck.Pressed = details.RequireCrew;
        UpdatePreview();
        UpdateDescriptionCount();
        UpdatePriceHint();
    }

    /// <summary>The form as details, sanitized the way the server will.</summary>
    public WFMappingShipDetails ReadDetails()
    {
        var details = new WFMappingShipDetails
        {
            Name = NameEdit.Text,
            Description = Rope.Collapse(DescriptionEdit.TextRope),
            Price = TryReadPrice(out var price) ? price : 0,
            Category = (VesselSize) CategoryOption.SelectedId,
            Group = (ShipyardConsoleUiKey) GroupOption.SelectedId,
            AutoEngines = EnginesAutoCheck.Pressed,
            Access = AccessEdit.Text.Trim(),
            RequireCrew = RequireCrewCheck.Pressed,
        };

        foreach (var (vesselClass, box) in _classBoxes)
        {
            if (box.Pressed)
                details.Classes.Add(vesselClass);
        }

        foreach (var (engine, box) in _engineBoxes)
        {
            if (box.Pressed)
                details.Engines.Add(engine);
        }

        return WFMappingExportLimits.Sanitize(details);
    }

    private bool TryReadPrice(out int price)
    {
        var text = PriceEdit.Text.Trim().Replace(",", string.Empty);
        if (text.Length == 0)
        {
            price = 0;
            return true;
        }

        return int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out price) &&
               price >= 0 && price <= WFMappingExportLimits.MaxPrice;
    }

    private void SetEnginesEnabled(bool enabled)
    {
        foreach (var box in _engineBoxes.Values)
        {
            box.Disabled = !enabled;
        }
    }

    private void UpdatePreview()
    {
        var name = WFMappingLibraryNames.TryNormalizeMapName(NameEdit.Text, out var normalized) ? normalized : MapName;
        PreviewLabel.Text = Loc.GetString("wf-mapping-export-details-preview",
            ("id", WFMappingShipNaming.VesselId(name)), ("file", WFMappingShipNaming.FileName(name)));
    }

    private void UpdateDescriptionCount()
    {
        DescriptionCount.Text = Loc.GetString("wf-mapping-export-details-description-count",
            ("count", DescriptionEdit.TextLength), ("max", WFMappingExportLimits.MaxDescriptionLength));
    }

    private void UpdatePriceHint()
    {
        if (!TryReadPrice(out _))
        {
            PriceHint.Text = Loc.GetString("wf-mapping-export-details-price-bad", ("max", WFMappingExportLimits.MaxPrice));
            PriceHint.FontColorOverride = ErrorColor;
            return;
        }

        PriceHint.FontColorOverride = null;
        if (_issues is not { Scope: WFMappingIssueScope.Ship } issues)
        {
            PriceHint.Text = Loc.GetString("wf-mapping-export-details-price-hint-unknown");
            return;
        }

        var appraisal = issues.Summary.Appraisal;
        PriceHint.Text = Loc.GetString("wf-mapping-export-details-price-hint",
            ("appraisal", ((int) Math.Round(appraisal)).ToString("N0", CultureInfo.InvariantCulture)),
            ("floor", WFMappingShipNaming.PriceFloor(appraisal).ToString("N0", CultureInfo.InvariantCulture)),
            ("suggested", WFMappingShipNaming.PriceFor(appraisal).ToString("N0", CultureInfo.InvariantCulture)));
    }

    private void UpdatePackageSummary()
    {
        if (_kind == WFMappingExportKind.Ship)
        {
            var details = ReadDetails();
            var file = WFMappingShipNaming.FileName(details.Name.Length > 0 ? details.Name : MapName);
            PackageSummary.SetMessage(Loc.GetString("wf-mapping-export-package-ship",
                ("grid", $"Resources/SharedMaps/_WF/Community/{file}.yml"),
                ("proto", $"Resources/Prototypes/_WF/Community/{file}.yml")));
            return;
        }

        var mapFile = WFMappingShipNaming.FileName(MapName);
        var levels = _issues?.Summary.Levels ?? 1;
        PackageSummary.SetMessage(Loc.GetString("wf-mapping-export-package-map",
            ("levels", levels),
            ("folder", $"Resources/Maps/_WF/Community/{mapFile}"),
            ("proto", $"Resources/Prototypes/_WF/Community/{mapFile}.yml")));
    }

    private static Label SubLabel(string text)
    {
        return new Label { Text = text, StyleClasses = { "LabelSubText" }, ClipText = true };
    }
}
