using System.Numerics;
using Content.Client.UserInterface.Screens;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.MappingMode.Screen;

/// <summary>
/// The screen mappers get in a session: the palette on the left, the viewport with the mode rail, quick-select bar
/// and cursor readout in the middle, and the properties tabs over the chat on the right. Built once at startup for
/// every client, so it only lays out its hosts; <see cref="WFMappingScreenUIController"/> fills them and collapses a
/// dock column whose panels are all undocked.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingScreen : InGameScreen
{
    private const float DockSplitWidth = 2f;

    /// <summary>The split each dock had been dragged to before it collapsed, or null when it was never dragged.</summary>
    private float? _leftSplit;

    private float? _rightSplit;

    /// <summary>Whether the palette column is hidden.</summary>
    public bool LeftCollapsed => !LeftDock.Visible;

    /// <summary>Whether the tabs and chat column is hidden; the chat then floats over the viewport.</summary>
    public bool RightCollapsed => !RightDock.Visible;

    public WFMappingScreen()
    {
        RobustXamlLoader.Load(this);

        SetAnchorPreset(ScreenSplit, LayoutPreset.Wide);
        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(TopBar, LayoutPreset.TopLeft, margin: 10);

        SetAnchorPreset(ModeRail, LayoutPreset.CenterTop);
        SetMarginTop(ModeRail, 10);
        SetGrowHorizontal(ModeRail, GrowDirection.Both);

        SetAnchorPreset(QuickBarHost, LayoutPreset.CenterBottom);
        SetMarginBottom(QuickBarHost, -10);
        SetMarginTop(QuickBarHost, -10);
        SetGrowHorizontal(QuickBarHost, GrowDirection.Both);
        SetGrowVertical(QuickBarHost, GrowDirection.Begin);

        SetAnchorPreset(StatusHost, LayoutPreset.BottomLeft);
        SetMarginLeft(StatusHost, 10);
        SetMarginBottom(StatusHost, -10);
        SetMarginTop(StatusHost, -10);
        SetGrowVertical(StatusHost, GrowDirection.Begin);
    }

    public override ChatBox ChatBox => Chat;

    /// <summary>Hides the palette column so the viewport takes its width, or brings it back.</summary>
    public void SetLeftCollapsed(bool collapsed)
    {
        Collapse(ScreenSplit, LeftDock, collapsed, ref _leftSplit);
    }

    /// <summary>
    /// Hides the tabs column so the viewport takes its width, or brings it back. The chat leaves with the column and
    /// floats at the viewport's top right meanwhile.
    /// </summary>
    public void SetRightCollapsed(bool collapsed)
    {
        Collapse(RightSplit, RightDock, collapsed, ref _rightSplit);
        if (collapsed == (Chat.Parent == ViewportContainer))
            return;

        Chat.Orphan();
        if (!collapsed)
        {
            RightColumn.AddChild(Chat);
            return;
        }

        ViewportContainer.AddChild(Chat);
        SetAnchorPreset(Chat, LayoutPreset.TopRight);
        SetMarginLeft(Chat, -430);
        SetMarginRight(Chat, -10);
        SetMarginTop(Chat, 50);
        SetMarginBottom(Chat, 290);
    }

    private static void Collapse(SplitContainer split, Control dock, bool collapsed, ref float? manualSplit)
    {
        if (dock.Visible != collapsed)
            return;

        if (collapsed)
        {
            manualSplit = split.State == SplitContainer.SplitState.Manual ? split.SplitCenter : null;
            dock.Visible = false;
            split.ResizeMode = SplitContainer.SplitResizeMode.NotResizable;
            split.SplitWidth = 0f;
            split.State = SplitContainer.SplitState.Auto;
            return;
        }

        dock.Visible = true;
        split.ResizeMode = SplitContainer.SplitResizeMode.RespectChildrenMinSize;
        split.SplitWidth = DockSplitWidth;
        if (manualSplit is { } center)
            split.SplitCenter = center;

        manualSplit = null;
    }

    /// <summary>The chat sits in the right dock and is sized by its split, so stored chat sizes don't apply.</summary>
    public override void SetChatSize(Vector2 size)
    {
    }
}
