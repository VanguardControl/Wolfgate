/// <summary>
/// The gamemaster's overwatch window: roster, sector map, camera feeds, context buttons and timeline around one
/// selection. It lives while it is open; closing it drops the server's subscription and every feed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFGodPanelWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPlayerManager _players = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly TimeSpan RadarInterval = TimeSpan.FromMilliseconds(250);

    private readonly WFGodPanelSystem _system;
    private readonly AdminRadarSystem _radar;
    private readonly RadarTeleportSystem _teleport;
    private readonly SharedTransformSystem _transform;

    private NetEntity? _selected;
    private bool _selectedIsGrid;
    private NetUserId? _selectedUser;

    private EntityUid? _radarEntity;
    private EntityUid _radarParent;
    private TimeSpan _nextRadar;
    private bool _relaidOut;

    public WFGodPanelWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _system = _entities.System<WFGodPanelSystem>();
        _radar = _entities.System<AdminRadarSystem>();
        _teleport = _entities.System<RadarTeleportSystem>();
        _transform = _entities.System<SharedTransformSystem>();

        MainSplit.SetSplitFractionOnNextArrange(0.76f);
        TopSplit.SetSplitFractionOnNextArrange(0.19f);
        CentreSplit.SetSplitFractionOnNextArrange(0.66f);

        SetupMap();

        Roster.Selected += (entity, isGrid) => Select(entity, isGrid);
        Roster.Watch += (entity, _) => Feeds.Watch(entity);
        Context.WatchRequested += entity => Feeds.Watch(entity);
        Feeds.SelectRequested += SelectEntity;
        Timeline.EventClicked += OnEventClicked;

        _system.StateUpdated += OnState;
        OnClose += OnWindowClosed;

        _system.Subscribe(true);
        OnState();
    }

    private void SetupMap()
    {
        LayoutContainer.SetAnchorPreset(RadarScreen, LayoutContainer.LayoutPreset.Wide);
        RadarScreen.WfPinDocks();
        RadarScreen.ForcePan = true;
        RadarScreen.OverlayDraw += DrawSelection;

        IffToggle.Pressed = RadarScreen.ShowIFF;
        IffDetailedToggle.Pressed = RadarScreen.ShowIFFDetailed;
        IffToggle.OnToggled += args => RadarScreen.ShowIFF = args.Pressed;
        IffDetailedToggle.OnToggled += args => RadarScreen.ShowIFFDetailed = args.Pressed;

        TrueIffToggle.Pressed = _radar.TrueIff;
        TrueIffToggle.OnToggled += args => _radar.TrueIff = args.Pressed;

        // The roster is the main way to find people, so the map starts with them marked.
        _radar.ShowPlayers = true;
        _radar.RequestPlayers(true);
        PlayersToggle.Pressed = true;
        PlayersToggle.OnToggled += args =>
        {
            _radar.ShowPlayers = args.Pressed;
            if (args.Pressed)
                _radar.RequestPlayers(true);
        };

        TeleportToggle.Pressed = _teleport.Enabled;
        TeleportToggle.OnToggled += args => _teleport.Enabled = args.Pressed;

        RecentreButton.OnPressed += _ =>
        {
            RadarScreen.Recentre();
            _radarEntity = null;
        };

        RadarScreen.OnKeyBindDown += OnMapClick;
    }

    private void OnMapClick(GUIBoundKeyEventArgs args)
    {
        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        if (_radar.ShowPlayers && RadarScreen.TryPickPlayer(args.RelativePixelPosition, out var player))
        {
            SelectEntity(player);
            return;
        }

        _teleport.RequestTeleport(RadarScreen.GetMouseCoordinatesFromCenter());
    }

    private void OnWindowClosed()
    {
        _system.StateUpdated -= OnState;
        Feeds.Detach();
        _system.Subscribe(false);
    }

    /// <summary>Selects a body or a grid; every pane follows.</summary>
    public void Select(NetEntity? entity, bool isGrid)
    {
        _selected = entity;
        _selectedIsGrid = isGrid;
        _selectedUser = null;

        if (entity != null && !isGrid && _system.State is { } state)
        {
            foreach (var player in state.Players)
            {
                if (player.Entity == entity)
                    _selectedUser = player.User;
            }
        }

        Roster.SetSelection(entity, isGrid);
        RefreshContext();
    }

    private void SelectEntity(NetEntity entity)
    {
        var isGrid = false;
        if (_system.State is { } state)
        {
            foreach (var grid in state.Grids)
            {
                if (grid.Entity == entity)
                    isGrid = true;
            }
        }

        Select(entity, isGrid);
    }

    private void OnEventClicked(WFGodEvent entry)
    {
        if (entry.Subject is { } subject)
            SelectEntity(subject);

        if (entry.Coordinates is { } coordinates)
            RadarScreen.CentreOn(_entities.GetCoordinates(coordinates));
    }

    private void OnState()
    {
        if (_system.State is not { } state)
        {
            TopBar.Update(null);
            return;
        }

        TopBar.Update(state);
        RefreshContext();
        Roster.Update(state);
        Feeds.Update(state);
        Timeline.Update();
    }

    /// <summary>Finds the selection in the latest state and hands it to the context bar.</summary>
    private void RefreshContext()
    {
        WFGodPlayer? player = null;
        WFGodGrid? grid = null;

        if (_system.State is { } state && _selected is { } selected)
        {
            if (_selectedIsGrid)
            {
                foreach (var candidate in state.Grids)
                {
                    if (candidate.Entity == selected)
                        grid = candidate;
                }
            }
            else
            {
                foreach (var candidate in state.Players)
                {
                    if (candidate.Entity == selected || player == null && _selectedUser == candidate.User)
                        player = candidate;
                }

                // The player took a new body, e.g. after a second chance: keep following them.
                if (player?.Entity is { } entity && entity != selected)
                {
                    _selected = entity;
                    Roster.SetSelection(entity, false);
                }
            }
        }

        Context.Show(player, grid);
    }

    /// <summary>Rings the selection on the map.</summary>
    private void DrawSelection(DrawingHandleScreen handle)
    {
        if (_system.State is not { } state || _selected is not { } selected)
            return;

        NetCoordinates? where = null;
        if (_selectedIsGrid)
        {
            foreach (var grid in state.Grids)
            {
                if (grid.Entity == selected)
                    where = grid.Coordinates;
            }
        }
        else
        {
            foreach (var player in state.Players)
            {
                if (player.Entity == selected || _selectedUser == player.User)
                    where = player.Coordinates;
            }
        }

        if (where is not { } netCoordinates)
            return;

        var coordinates = _entities.GetCoordinates(netCoordinates);
        if (!coordinates.IsValid(_entities)
            || !RadarScreen.TryGetViewPosition(_transform.ToMapCoordinates(coordinates), out var position))
            return;

        var scale = RadarScreen.UIScale;
        handle.DrawCircle(position, 14f * scale, WFGodPanelText.Gold, false);
        handle.DrawCircle(position, 16f * scale, WFGodPanelText.Gold.WithAlpha(0.4f), false);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // The engine re-arranges a control only when its own rect changes, so panes whose children were measured
        // before the styles gave them a height keep that first layout. One pass after the window has its size
        // lays everything out again.
        if (!_relaidOut && Size.Y > 0)
        {
            _relaidOut = true;
            Relayout(this);
        }

        TeleportToggle.Disabled = !_teleport.CanTeleport();
        if (_radar.ShowPlayers)
            _radar.RequestPlayers();

        UpdateRadarState();
    }

    private static void Relayout(Control control)
    {
        foreach (var child in control.Children)
            Relayout(child);

        control.InvalidateMeasure();
        control.InvalidateArrange();
    }

    /// <summary>
    /// The window has no console, so the scanner is fed a state built from the admin's own entity whenever that,
    /// or what it is standing on, changes.
    /// </summary>
    private void UpdateRadarState()
    {
        if (_timing.RealTime < _nextRadar)
            return;

        _nextRadar = _timing.RealTime + RadarInterval;

        if (_players.LocalEntity is not { } uid || !_entities.TryGetComponent(uid, out TransformComponent? xform))
            return;

        if (_radarEntity == uid && _radarParent == xform.ParentUid)
            return;

        _radarEntity = uid;
        _radarParent = xform.ParentUid;

        RadarScreen.SetConsole(uid);
        var angle = xform.MapID == MapId.Nullspace ? Angle.Zero : _transform.GetWorldRotation(uid);
        var state = new NavInterfaceState(
            AdminRadarControl.AdminMaxRange,
            _entities.GetNetCoordinates(xform.Coordinates),
            angle,
            new Dictionary<NetEntity, List<DockingPortState>>(),
            InertiaDampeningMode.Dampen);
        RadarScreen.UpdateAdminState(state);
    }
}
