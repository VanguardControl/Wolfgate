using System.Linq;
using Content.Client._WG.Stylesheets;
using Content.Client.Options.UI;
using Content.Shared._WG.Camera;
using Content.Shared._WG.CCVar;
using Content.Shared._WG.CombatFacing;
using Content.Shared._WG.Newbie;
using Content.Shared._WG.Wilderness;
using Content.Shared._WG.Wolfmed.CCVar;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WG.Options.UI.Tabs;

/// <summary>The Wolfgate Interface tab: UI style, cursor, ship console, zone indicator and medical readout settings.</summary>
[GenerateTypedNameReferences]
public sealed partial class WGInterfaceTab : Control
{
    public WGInterfaceTab()
    {
        RobustXamlLoader.Load(this);

        var styles = WolfgateSkins.All
            .Select(skin => new OptionDropDownCVar<string>.ValueOption(skin.Id, Loc.GetString(skin.Name)))
            .ToList();
        Control.AddOptionDropDown(WolfgateCVars.UiStyle, DropDownWolfgateStyle, styles);
        Control.AddOptionCheckBox(WolfgateCVars.WindowPopout, WindowPopoutCheckBox);
        Control.AddOptionCheckBox(CCVars.DetailedExamine, DetailedExamineCheckBox);
        Control.AddOptionCheckBox(WGNewbieCVars.ShowTag, ShowNewbieTagCheckBox);

        WgAddScreentipOptions();
        Control.AddOptionCheckBox(CCVars.OutlineEnabled, OutlineCheckBox);
        Control.AddOptionCheckBox(WGCombatFacingCVars.FaceCursor, CombatFaceCursorCheckBox);

        Control.AddOptionCheckBox(WolfgateCVars.CockpitAutoEnter, CockpitAutoEnterCheckBox);
        Control.AddOptionCheckBox(WGCameraCVars.DefaultNorth, DefaultNorthCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarSmartTags, RadarSmartTagsCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarIconsOnly, RadarIconsOnlyCheckBox);
        Control.AddOptionCheckBox(WolfgateCVars.RadarHoverReveal, RadarHoverRevealCheckBox);

        var zoneShow = new List<OptionDropDownCVar<string>.ValueOption>
        {
            new(WildernessCVars.ShowAlways, Loc.GetString("ui-options-wg-wilderness-always")),
            new(WildernessCVars.ShowDanger, Loc.GetString("ui-options-wg-wilderness-danger")),
            new(WildernessCVars.ShowOff, Loc.GetString("ui-options-wg-wilderness-off")),
        };
        Control.AddOptionDropDown(WildernessCVars.Banner, WildernessBannerDropDown, zoneShow);
        Control.AddOptionDropDown(WildernessCVars.Titles, WildernessTitlesDropDown, zoneShow);
        Control.AddOptionDropDown(WildernessCVars.Sounds, WildernessSoundsDropDown, zoneShow);
        foreach (var dropDown in new[] { WildernessBannerDropDown, WildernessTitlesDropDown, WildernessSoundsDropDown })
        {
            dropDown.Button.ToolTip = Loc.GetString("ui-options-wg-wilderness-danger-tooltip");
        }
        Control.AddOptionDropDown(WildernessCVars.ScreenBorder, WildernessBorderDropDown, new List<OptionDropDownCVar<string>.ValueOption>
        {
            new(WildernessCVars.BorderWilderness, Loc.GetString("ui-options-wg-wilderness-border-wilderness")),
            new(WildernessCVars.BorderMarked, Loc.GetString("ui-options-wg-wilderness-border-marked")),
            new(WildernessCVars.ShowOff, Loc.GetString("ui-options-wg-wilderness-off")),
        });
        Control.AddOptionPercentSlider(WildernessCVars.ScreenBorderIntensity, WildernessBorderIntensitySlider, 0.1f, 1f);
        Control.AddOptionCheckBox(WildernessCVars.ZoneChat, WildernessChatCheckBox);
        Control.AddOptionCheckBox(WildernessCVars.RadarRings, WildernessRingsCheckBox);

        Control.AddOptionCheckBox(WolfmedCVars.CritHeartbeat, CritHeartbeatCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.DyingEffects, DyingEffectsCheckBox);
        Control.AddOptionCheckBox(WolfmedCVars.SyntheticHud, SyntheticHudCheckBox);
        Control.AddOptionPercentSlider(WolfmedCVars.SyntheticHudScale, SyntheticHudScaleSlider, 0.6f, 2.5f);

        Control.Initialize();
    }
}
