    private static readonly TimeSpan RefreshInterval = TimeSpan.FromSeconds(15);
    private static readonly TimeSpan CollisionShown = TimeSpan.FromSeconds(10);

    /// <summary>How long the server holds back another request for help on a ticket; the button rests as long.</summary>
    private static readonly TimeSpan AssistCooldown = TimeSpan.FromSeconds(30);

    /// <summary>With no mouse or typing in the panel this long, the staffer stops counting as looking at its ticket.</summary>
    private static readonly TimeSpan IdleAfter = TimeSpan.FromMinutes(5);

    private readonly WGTicketAHelpUIHandler _handler;
    private readonly AHelpTicketClientSystem _tickets;
    private readonly AdminSystem _adminSystem;
    private readonly Dictionary<Button, ConfirmationData> _confirmations = new();
    private readonly List<WGAHelpMacroPrototype> _macros = new();

    private int? _selectedKey;
    private TimeSpan _sinceRefresh;
    private TimeSpan _collisionLeft;
    private WGLoadoutGrantWindow? _loadoutWindow;
    private WGAHelpMacroPrototype? _pendingMacro;

    /// <summary>When each ticket may ask for help again, by key, so switching tickets doesn't reset it.</summary>
    private readonly Dictionary<int, TimeSpan> _assistUntil = new();

    /// <summary>Quick actions that need the player online or in a body, enabled to match.</summary>
    private readonly List<(Button Button, Func<bool> Usable)> _actionStates = new();

    private TimeSpan _now;
    private TimeSpan _lastActive;
    private bool _idle;

    /// <summary>Whether the panel is on screen, so the ticket it shows counts as being looked at.</summary>
    private bool _shown = true;

    /// <summary>The player whose ahelp is shown.</summary>
    public NetUserId? SelectedPlayer { get; private set; }

    public AHelpTicketsControl(WGTicketAHelpUIHandler handler)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _handler = handler;
        _tickets = _entities.System<AHelpTicketClientSystem>();
        _adminSystem = _entities.System<AdminSystem>();

        TicketList.GenerateItem = GenerateRow;
        TicketList.ItemPressed = OnRowPressed;

        SearchBox.OnTextChanged += _ => Repopulate();
        SearchBox.OnTextEntered += args => SearchStored(args.Text);
        foreach (var filter in new[] { FilterMine, FilterOnline, FilterNotes, FilterClosed })
        {
            filter.OnToggled += _ => Repopulate();
        }

        ClaimButton.OnPressed += _ => Act(AHelpTicketAction.Claim);
        UnclaimButton.OnPressed += _ => Act(AHelpTicketAction.Unclaim);
        ResolveButton.OnPressed += _ => Act(AHelpTicketAction.Resolve);
        RejectButton.OnPressed += _ => Act(AHelpTicketAction.Reject);
        IcButton.OnPressed += _ => Act(AHelpTicketAction.IcIssue);
        ReopenButton.OnPressed += _ => Act(AHelpTicketAction.Reopen);
        AssistButton.OnPressed += _ => Assist();
        ExportButton.OnPressed += _ => Export();
        AdminOnly.OnToggled += args => PlaySound.Disabled = args.Pressed;
        MacroSend.OnPressed += _ => ConfirmMacro();
        MacroCancel.OnPressed += _ => ShowMacroConfirm(null);

        // What the player is shown when staff close their ticket each way.
        ResolveButton.ToolTip = CloseTooltip("wg-bwoink-resolved-player");
        RejectButton.ToolTip = CloseTooltip("wg-ahelp-ticket-closed-player-rejected");
        IcButton.ToolTip = CloseTooltip("wg-ahelp-ticket-closed-player-ic");

        SetupMacros();

        _tickets.TicketsChanged += OnTicketsChanged;
        _tickets.CardReceived += OnCardReceived;
        _adminSystem.PlayerListChanged += OnPlayersChanged;

        Repopulate();
        UpdateSelection();
    }

    private static string CloseTooltip(string playerMessage)
    {
        return Loc.GetString("wg-ahelp-tickets-close-tooltip",
            ("message", FormattedMessage.RemoveMarkupPermissive(Loc.GetString(playerMessage))));
    }

    /// <summary>A line arrived in a player's ahelp.</summary>
    public void OnLine(NetUserId player)
    {
        Repopulate();
    }

    /// <summary>Shows the player's newest ticket, or their channel when they have none yet.</summary>
    public void OpenPlayer(NetUserId player)
    {
        var ticket = _tickets.LatestFor(player);
        if (ticket != null)
        {
            OpenTicket(ticket.Key);
            return;
        }

        _selectedKey = null;
        ShowPlayer(player);
    }

    /// <summary>Shows a ticket of this round by its key; one from an earlier round says where to find it instead.</summary>
    public void OpenTicket(int key)
    {
        if (!_tickets.Tickets.ContainsKey(key))
        {
            Placeholder.Text = Loc.GetString("wg-ahelp-tickets-link-gone");
            return;
        }

        Placeholder.Text = Loc.GetString("wg-ahelp-tickets-none-selected");
        Select(key);
        TicketList.Select(new TicketRowData(key));
    }

    /// <summary>The panel came on screen.</summary>
    public void Shown()
    {
        _shown = true;
        ReportView();
    }

    /// <summary>The panel left the screen; the staffer is no longer looking at its ticket.</summary>
    public void Hidden()
    {
        _shown = false;
        ReportView();
    }

    /// <summary>Warns when someone other than the player types in the selected ahelp.</summary>
    public void PeopleTypingUpdated(BwoinkPlayerTypingUpdated args)
    {
        if (!args.Typing || args.Channel != SelectedPlayer || args.PlayerName == _player.LocalSession?.Name)
            return;

        if (CurrentTicket() is { } ticket && args.PlayerName == ticket.Username)
            return;

        Collision.Text = Loc.GetString("wg-ahelp-tickets-collision", ("name", args.PlayerName));
        Collision.Visible = true;
        _collisionLeft = CollisionShown;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var delta = TimeSpan.FromSeconds(args.DeltaSeconds);
        _now += delta;
        if (_collisionLeft > TimeSpan.Zero)
        {
            _collisionLeft -= delta;
            if (_collisionLeft <= TimeSpan.Zero)
                Collision.Visible = false;
        }

        if (CurrentTicket() is { } shown && _assistUntil.TryGetValue(shown.Key, out var until) && _now >= until)
        {
            _assistUntil.Remove(shown.Key);
            UpdateAssist();
        }

        // Looking means the mouse is over the panel or the staffer is typing in it; idle a while, they aren't.
        if (Inside(UserInterfaceManager.CurrentlyHovered) || Inside(UserInterfaceManager.KeyboardFocused))
            _lastActive = _now;

        var idle = _now - _lastActive > IdleAfter;
        if (idle != _idle)
        {
            _idle = idle;
            ReportView();
        }

        _sinceRefresh += delta;
        if (_sinceRefresh < RefreshInterval)
            return;

        // Ages and stale marks move with the clock.
        _sinceRefresh = TimeSpan.Zero;
        Repopulate();
    }

    private void OnTicketsChanged(AHelpTicketInfo? ticket)
    {
        Repopulate();

        // The chat belongs to the player, not the ticket: a line sent while a closed ticket is shown opens a new one,
        // and the panel moves to it so its buttons act on the ticket the chat is now part of.
        if (ticket != null && ticket.Player == SelectedPlayer && !ticket.State.IsClosed() && ticket.Key != _selectedKey
            && (CurrentTicket() is not { } shown || shown.State.IsClosed()))
        {
            OpenTicket(ticket.Key);
            return;
        }

        if (ticket == null || ticket.Player == SelectedPlayer)
            UpdateSelection();
    }

    private void OnCardReceived(AHelpTicketPlayerCardMessage card)
    {
        if (card.Player != SelectedPlayer)
            return;

        UpdateSelection();
        BuildShips(card);
    }

    private void OnPlayersChanged(List<PlayerInfo> players)
    {
        if (SelectedPlayer != null)
            UpdateCard();
    }

    /// <summary>Whether a control is this panel or inside it.</summary>
    private bool Inside(Control? control)
    {
        for (var at = control; at != null; at = at.Parent)
        {
            if (at == this)
                return true;
        }

        return false;
    }

    private void OnRowPressed(BaseButton.ButtonEventArgs args, ListData data)
    {
        if (data is TicketRowData row)
            Select(row.Key);
    }

    private void Select(int key)
    {
        if (!_tickets.Tickets.TryGetValue(key, out var ticket))
            return;

        if (_selectedKey != key)
        {
            // Admin only is a choice for one ticket; it doesn't follow the staffer to the next player.
            AdminOnly.Pressed = false;
            PlaySound.Disabled = false;
            ShowMacroConfirm(null);

            // The card is fetched again per ticket, so bank, notes and ships are current.
            if (SelectedPlayer == ticket.Player)
                _tickets.RequestCard(ticket.Player);
        }

        _selectedKey = key;
        ShowPlayer(ticket.Player);
    }

    private void ShowPlayer(NetUserId player)
    {
        var changed = SelectedPlayer != player;
        SelectedPlayer = player;
        _handler.ShowPanel(player);
        if (changed)
        {
            Collision.Visible = false;
            Ships.RemoveAllChildren();
            ShipsHeading.Visible = false;
            _loadoutWindow?.Close();
            _tickets.RequestCard(player);
            BuildActions();
        }

        UpdateSelection();
    }

    /// <summary>The selected ticket, or the selected player's newest one once it exists.</summary>
    private AHelpTicketInfo? CurrentTicket()
    {
        if (_selectedKey is { } key && _tickets.Tickets.TryGetValue(key, out var ticket))
            return ticket;

        if (SelectedPlayer is not { } player || _tickets.LatestFor(player) is not { } latest)
            return null;

        _selectedKey = latest.Key;
        return latest;
    }

    private void Act(AHelpTicketAction action)
    {
        if (CurrentTicket() is { } ticket)
            _tickets.Act(ticket.Key, action);
    }

    private void Assist()
    {
        if (CurrentTicket() is not { } ticket)
            return;

        _tickets.Assist(ticket.Key);
        _assistUntil[ticket.Key] = _now + AssistCooldown;
        UpdateAssist();
    }

    private void UpdateAssist()
    {
        AssistButton.Disabled = CurrentTicket() is not { } ticket || ticket.State.IsClosed() || _assistUntil.ContainsKey(ticket.Key);
    }

    /// <summary>Saves the shown chat to a text file, headed with the ticket and player.</summary>
    private async void Export()
    {
        if (SelectedPlayer is not { } player || !_handler.TryGetChannel(player, out var panel))
            return;

        var text = new StringBuilder();
        if (CurrentTicket() is { } ticket)
        {
            text.AppendLine(Loc.GetString("wg-ahelp-export-header",
                ("number", ticket.Number),
                ("round", ticket.RoundId),
                ("username", ticket.Username),
                ("character", ticket.Character),
                ("state", ticket.State.ToString())));
        }
        else if (Info() is { } info)
        {
            text.AppendLine($"{info.CharacterName} ({info.Username})");
        }

        text.AppendLine();
        text.Append(panel.Transcript());

        var file = await _fileDialog.SaveFile(new FileDialogFilters(new FileDialogFilters.Group("txt")));
        if (file == null)
            return;

        try
        {
            await using var writer = new StreamWriter(file.Value.fileStream, Encoding.UTF8);
            await writer.WriteAsync(text.ToString());
        }
        catch (Exception e)
        {
            Logger.GetSawmill("wg.ahelp").Error($"Saving an ahelp transcript failed: {e}");
        }
    }

    private void SearchStored(string text)
    {
        if (!string.IsNullOrWhiteSpace(text))
            _handler.OpenHistory().ShowSearch(text.Trim());
    }

    /// <summary>Tells the server which ticket is on screen, or none while the panel is closed.</summary>
    private void ReportView()
    {
        _tickets.View(_shown && !_idle && !Disposed ? CurrentTicket()?.Key : null);
    }

    #region List

    private void Repopulate()
    {
        var me = _player.LocalUser;
        var search = SearchBox.Text.Trim();
        var shown = _tickets.Tickets.Values.Where(t => Matches(t, search, me)).ToList();

        var data = new List<ListData>();
        AddGroup(data, "wg-ahelp-tickets-group-unclaimed",
            shown.Where(t => t.State == AHelpTicketState.Open).OrderBy(t => t.Opened).ThenBy(t => t.Key));
        AddGroup(data, "wg-ahelp-tickets-group-mine",
            shown.Where(t => t.State == AHelpTicketState.Claimed && t.Assignee == me).OrderBy(t => t.Opened).ThenBy(t => t.Key));
        AddGroup(data, "wg-ahelp-tickets-group-claimed",
            shown.Where(t => t.State == AHelpTicketState.Claimed && t.Assignee != me).OrderBy(t => t.Opened).ThenBy(t => t.Key));
        AddGroup(data, "wg-ahelp-tickets-group-closed",
            shown.Where(t => t.State.IsClosed()).OrderByDescending(t => t.Opened).ThenByDescending(t => t.Key));

        TicketList.PopulateList(data);
        EmptyLabel.Visible = data.Count == 0;
        EmptyLabel.Text = Loc.GetString(_tickets.Tickets.Count == 0 ? "wg-ahelp-tickets-empty" : "wg-ahelp-tickets-filtered");
    }

    private bool Matches(AHelpTicketInfo ticket, string search, NetUserId? me)
    {
        if (!FilterClosed.Pressed && ticket.State.IsClosed())
            return false;
        if (FilterMine.Pressed && ticket.Assignee != me)
            return false;
        if (FilterOnline.Pressed && !ticket.Online)
            return false;
        if (FilterNotes.Pressed && !ticket.HasNotes)
            return false;
        if (search.Length == 0)
            return true;

        var number = search.TrimStart('#');
        return ticket.Number > 0 && ticket.Number.ToString() == number
               || ticket.Username.Contains(search, StringComparison.OrdinalIgnoreCase)
               || ticket.Character.Contains(search, StringComparison.OrdinalIgnoreCase)
               || (ticket.AssigneeName?.Contains(search, StringComparison.OrdinalIgnoreCase) ?? false);
    }

    private static void AddGroup(List<ListData> data, string title, IEnumerable<AHelpTicketInfo> tickets)
    {
        var rows = tickets.Select(t => new TicketRowData(t.Key)).ToList();
        if (rows.Count == 0)
            return;

        data.Add(new TicketGroupData(Loc.GetString(title), rows.Count));
        data.AddRange(rows);
    }

    private void GenerateRow(ListData data, ListContainerButton button)
    {
        var label = new Label { ClipText = true, HorizontalExpand = true };
        button.AddChild(label);
        button.AddStyleClass(ListContainer.StyleClassListContainerButton);

        switch (data)
        {
            case TicketGroupData group:
                label.Text = $"{group.Title} ({group.Count})";
                label.StyleClasses.Add("LabelSubText");
                button.Disabled = true;
                break;
            case TicketRowData row when _tickets.Tickets.TryGetValue(row.Key, out var ticket):
                label.Text = RowText(ticket);
                label.FontColorOverride = RowColor(ticket);
                button.ToolTip = RowTooltip(ticket);
                break;
        }
    }

    /// <summary>
    /// A ticket's row: the marks that decide who picks it up come first (unread, number, age, notes, viewers, who has
    /// it), and the name last, since a narrow list cuts the end off.
    /// </summary>
    private string RowText(AHelpTicketInfo ticket)
    {
        var minutes = (int) Math.Max(0, (DateTime.UtcNow - ticket.Opened).TotalMinutes);
        var unread = _handler.TryGetChannel(ticket.Player, out var panel) && panel.Unread > 0 ? $"●{panel.Unread} " : string.Empty;
        var category = ticket.Category == AHelpCategory.Gameplay ? "[G] " : string.Empty;
        var notes = ticket.HasNotes ? " ✎" : string.Empty;
        var watched = ticket.Viewers.Count > 0 ? $" ◉{ticket.Viewers.Count}" : string.Empty;
        var offline = ticket.Online ? string.Empty : $" ({Loc.GetString("wg-ahelp-tickets-offline")})";
        var assignee = ticket.State == AHelpTicketState.Claimed && ticket.AssigneeName != null ? $" [{ticket.AssigneeName}]" : string.Empty;
        var name = ticket.Character.Length > 0 ? $"{ticket.Character} ({ticket.Username})" : ticket.Username;

        return $"{unread}{NumberText(ticket)} {Loc.GetString("wg-ahelp-tickets-age", ("minutes", minutes))}{notes}{watched}{assignee} · {category}{name}{offline}";
    }

    /// <summary>Everything a row may cut off, in full.</summary>
    private static string RowTooltip(AHelpTicketInfo ticket)
    {
        var lines = new List<string> { ticket.Character.Length > 0 ? $"{ticket.Character} ({ticket.Username})" : ticket.Username };
        if (ticket.State == AHelpTicketState.Claimed && ticket.AssigneeName != null)
            lines.Add(Loc.GetString("wg-ahelp-tickets-row-assignee", ("name", ticket.AssigneeName)));
        if (ticket.Viewers.Count > 0)
            lines.Add(Loc.GetString("wg-ahelp-tickets-viewers", ("names", string.Join(", ", ticket.Viewers))));
        if (ticket.HasNotes)
            lines.Add(Loc.GetString("wg-ahelp-tickets-row-notes"));
        return string.Join("\n", lines);
    }

    private Color? RowColor(AHelpTicketInfo ticket)
    {
        if (ticket.State.IsClosed())
            return Color.Gray;

        var stale = _cfg.GetCVar(AHelpTicketCVars.StaleMinutes);
        if (ticket.State == AHelpTicketState.Open && stale > 0 && DateTime.UtcNow - ticket.LastPlayerMessage > TimeSpan.FromMinutes(stale))
            return Color.FromHex("#ffb347");

        return ticket.State == AHelpTicketState.Open ? Color.FromHex("#ffe08a") : null;
    }

    private static string NumberText(AHelpTicketInfo ticket)
    {
        return ticket.Number > 0
            ? Loc.GetString("wg-ahelp-tickets-number", ("number", ticket.Number))
            : Loc.GetString("wg-ahelp-tickets-number-pending");
    }

