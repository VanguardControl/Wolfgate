    #region Macros

    private void SetupMacros()
    {
        // A macro whose command this staffer can't run is left out, so its reply never promises what didn't happen.
        _macros.AddRange(_proto.EnumeratePrototypes<WGAHelpMacroPrototype>()
            .Where(CanRun)
            .OrderBy(m => m.Order)
            .ThenBy(m => m.ID));

        Macros.AddItem(Loc.GetString("wg-ahelp-tickets-macros"), 0);
        for (var i = 0; i < _macros.Count; i++)
        {
            Macros.AddItem(Loc.GetString(_macros[i].Name), i + 1);
        }

        Macros.OnItemSelected += args =>
        {
            Macros.SelectId(0);
            if (args.Id > 0 && args.Id <= _macros.Count)
                ApplyMacro(_macros[args.Id - 1]);
        };
    }

    private bool CanRun(WGAHelpMacroPrototype macro)
    {
        return macro.Command is not { } command
               || _admin.CanCommand(command.Split(' ', 2, StringSplitOptions.RemoveEmptyEntries).FirstOrDefault() ?? string.Empty);
    }

    /// <summary>Sends a macro's reply to the selected player, then applies its action and command.</summary>
    public void ApplyMacro(WGAHelpMacroPrototype macro)
    {
        if (SelectedPlayer is not { } player || !CanRun(macro))
            return;

        // The player's own tickets decide where the macro goes, not which ticket is selected: a closed one picked from
        // the list for reading must not swallow a macro meant for the open one, which may be older if it was reopened.
        var info = Info();
        var ticket = _tickets.LatestFor(player);
        if (macro.Text is { } text)
        {
            // The server sends the reply and applies the macro to the ticket that reply lands on.
            var character = info?.CharacterName ?? ticket?.Character ?? string.Empty;
            _tickets.SendMacroReply(player, Loc.GetString(text, ("player", character)),
                PlaySound.Pressed && !AdminOnly.Pressed, AdminOnly.Pressed, macro.ID, macro.Action);
        }
        else if (_tickets.OpenFor(player) is { } open)
        {
            UseMacro(open, macro);
        }

        if (macro.Command is { } command)
        {
            _console.ExecuteCommand(command
                .Replace("{username}", info?.Username ?? ticket?.Username ?? string.Empty)
                .Replace("{entity}", info?.NetEntity?.ToString() ?? string.Empty));
        }
    }

    private void UseMacro(AHelpTicketInfo ticket, WGAHelpMacroPrototype macro)
    {
        _tickets.MacroUsed(ticket.Key, macro.ID);
        if (macro.Action is { } action)
            _tickets.Act(ticket.Key, action);
    }

