    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        _tickets.View(null);
        _loadoutWindow?.Close();
        _tickets.TicketsChanged -= OnTicketsChanged;
        _tickets.CardReceived -= OnCardReceived;
        _adminSystem.PlayerListChanged -= OnPlayersChanged;
    }
}

