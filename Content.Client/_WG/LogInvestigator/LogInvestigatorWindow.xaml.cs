/// <summary>
/// The log investigator: a query panel (round time, players, entities, categories, impact, text, presets), a result
/// list that wraps each log, folds bursts of the same event into one row and stays live on the current round, and a
/// pane with the selected log's entities and the scripted reports.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LogInvestigatorWindow : DefaultWindow
{
    [Dependency] private IClientConsoleHost _console = default!;
    [Dependency] private IClipboardManager _clipboard = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    /// <summary>How close in time repeats must be to fold into one row.</summary>
    private static readonly TimeSpan CollapseWindow = TimeSpan.FromSeconds(10);

    /// <summary>How often a live newest-first list asks for newer logs.</summary>
    private static readonly TimeSpan LiveInterval = TimeSpan.FromSeconds(5);

    private readonly List<LogRow> _rows = new();
    private readonly HashSet<int> _expanded = new();

    /// <summary>Newer logs that came in while the list was scrolled down, shown when the staffer asks.</summary>
    private readonly List<LogRow> _pending = new();

    private readonly List<LogRowControl> _rowControls = new();
    private readonly List<(WGLogCategoryPrototype Category, CheckBox Box, List<(LogType Type, CheckBox Box)> Types)> _categories = new();
    private readonly Dictionary<LogImpact, Button> _impacts = new();
    private readonly List<LogPlayer> _players = new();
    private readonly List<Guid> _chosenPlayers = new();
    private readonly List<int> _chosenEntities = new();

    private LogInvestigatorEuiState? _state;

    /// <summary>The query the shown results came from, for loading more of them.</summary>
    private LogQuery? _loadedQuery;
    private bool _hasMore;
    private int? _total;
    private LogRow? _selected;
    private LogQuery? _reportFilter;

    /// <summary>Bumped by each search, so a live poll sent for an older one is dropped.</summary>
    private int _searchGeneration;
    private int _pollGeneration = -1;
    private bool _awaitingFirstPage;
    private TimeSpan _sinceLive;

    /// <summary>A query, after the log with this id; with the flag, the logs newer than it.</summary>
    public event Action<LogQuery, int?, bool>? QueryRequested;
    public event Action<int>? RoundRequested;
    public event Action<LogReportKind, LogQuery, LogPoint?, int>? ReportRequested;

    public LogInvestigatorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        RoundBox.InitDefaultButtons();
        RoundBox.IsValid = round => round > 0 && round <= (_state?.CurrentRound ?? int.MaxValue);
        RoundBox.ValueChanged += args => RoundRequested?.Invoke(args.Value);
        CurrentRoundButton.OnPressed += _ =>
        {
            if (_state != null)
                RoundBox.Value = _state.CurrentRound;
        };

        PlayerSearch.OnTextChanged += _ => ShowPlayerMatches();
        TextBox.OnTextEntered += _ => Search();
        SearchButton.OnPressed += _ => Search();
        MoreButton.OnPressed += _ => More();
        CopyButton.OnPressed += _ => Copy();
        CollapseBox.OnToggled += _ => ShowRows();
        EncounterButton.OnPressed += _ => ReportRequested?.Invoke(LogReportKind.Encounter, BuildQuery(), null, Radius());
        TimelineButton.OnPressed += _ => ReportRequested?.Invoke(LogReportKind.Timeline, BuildQuery(), null, Radius());
        NewLogsButton.OnPressed += _ => ShowPending();
        ReportFilterButton.OnPressed += _ => ApplyReportFilter();

        BuildImpacts();
        BuildCategories();
        BuildPresets();
        UpdateChips();
        ShowDetail();
    }

    #region State and results

    public void SetState(LogInvestigatorEuiState state)
    {
        var roundChanged = _state?.RoundId != state.RoundId;
        var hadRound = _state != null;
        _state = state;
        _players.Clear();
        _players.AddRange(state.Players);

        if (RoundBox.Value != state.RoundId)
            RoundBox.OverrideValue(state.RoundId);

        if (roundChanged)
        {
            _chosenPlayers.RemoveAll(p => _players.All(known => known.Id != p));
            UpdateChips();

            // Another round's rows would be timed against this round's start; they go, and the round is searched anew.
            if (hadRound)
                ClearResults();
        }

        ShowPlayerMatches();
        SearchButton.Disabled = state.Loading;
        UpdateCount();

        // Opened with nothing filled in: show the newest logs straight away.
        if (!state.Loading && _loadedQuery == null)
            Search();
    }

    /// <summary>Fills in the query from a ticket, verb or panel, runs it, and builds the report asked for.</summary>
    public void Prefill(LogQuery query, LogReportKind? report)
    {
        _chosenPlayers.Clear();
        _chosenPlayers.AddRange(query.Players);
        _chosenEntities.Clear();
        _chosenEntities.AddRange(query.Entities);
        FromEdit.Text = query.FromSeconds is { } from ? LogInvestigatorText.RoundTime(TimeSpan.FromSeconds(from)) : string.Empty;
        ToEdit.Text = query.ToSeconds is { } to ? LogInvestigatorText.RoundTime(TimeSpan.FromSeconds(to)) : string.Empty;
        TextBox.Text = query.Text ?? string.Empty;
        AllPlayersBox.Pressed = query.AllPlayers;
        UpdateChips();
        Search();

        if (report is { } kind)
            ReportRequested?.Invoke(kind, BuildQuery(), null, Radius());
    }

    public void AddPage(LogInvestigatorPageMsg page)
    {
        if (page.Newer)
        {
            AddNewer(page);
            return;
        }

        if (page.Replace)
        {
            _rows.Clear();
            _expanded.Clear();
            _pending.Clear();
            _total = page.Total;
            _selected = null;
            _awaitingFirstPage = false;
            _sinceLive = TimeSpan.Zero;
            ShowDetail();
            UpdatePending();
        }

        _rows.AddRange(page.Rows);
        _hasMore = page.HasMore;
        MoreButton.Disabled = !_hasMore;
        ShowRows();
        UpdateCount();
    }

    /// <summary>Empties the list, the detail pane and the report, so the next search starts clean.</summary>
    private void ClearResults()
    {
        _rows.Clear();
        _pending.Clear();
        _expanded.Clear();
        _selected = null;
        _total = null;
        _hasMore = false;
        _loadedQuery = null;
        _reportFilter = null;
        MoreButton.Disabled = true;
        ReportTitle.Text = string.Empty;
        ReportFilterButton.Visible = false;
        Report.RemoveAllChildren();
        ShowRows();
        ShowDetail();
        UpdatePending();
        UpdateCount();
    }

    /// <summary>
    /// Logs newer than the top of the list. They go straight in when the list is at the top; otherwise they wait
    /// behind a button so the rows being read don't move. Too many to fit a page means a fresh search instead.
    /// </summary>
    private void AddNewer(LogInvestigatorPageMsg page)
    {
        if (_pollGeneration != _searchGeneration || _awaitingFirstPage)
            return;

        // Rerun what is on screen, not whatever the filters were edited to since.
        if (page.HasMore)
        {
            if (_loadedQuery is { } loaded)
                Search(loaded);
            return;
        }

        var newest = Newest();
        _pending.InsertRange(0, page.Rows.Where(r => r.Id > newest));

        // Rows only move on their own when nobody is reading them: at the top, nothing picked, the mouse elsewhere.
        if (ResultsScroll.GetScrollValue().Y <= 1 && _selected == null && !Inside(UserInterfaceManager.CurrentlyHovered, ResultsScroll))
            ShowPending();
        else
            UpdatePending();
    }

    /// <summary>Moves the waiting newer logs to the top of the list.</summary>
    private void ShowPending()
    {
        if (_pending.Count == 0)
            return;

        var count = _pending.Count;
        _rows.InsertRange(0, _pending);
        _pending.Clear();

        // Folded runs are kept by where they start, which moved down.
        var expanded = _expanded.Select(i => i + count).ToList();
        _expanded.Clear();
        _expanded.UnionWith(expanded);
        if (_total is { } total)
            _total = total + count;

        // Only the new rows are built; they go above the ones already shown.
        var fresh = BuildRows(0, count);
        for (var i = 0; i < fresh.Count; i++)
        {
            Results.AddChild(fresh[i]);
            fresh[i].SetPositionInParent(i);
        }

        _rowControls.InsertRange(0, fresh);
        UpdateCount();
        UpdatePending();
    }

    private void UpdatePending()
    {
        NewLogsButton.Visible = _pending.Count > 0;
        NewLogsButton.Text = Loc.GetString("wg-log-investigator-new-logs", ("count", _pending.Count));
    }

    /// <summary>The id of the newest log on screen or waiting, or 0 when there are none.</summary>
    private int Newest()
    {
        if (_pending.Count > 0)
            return _pending[0].Id;

        return _rows.Count > 0 ? _rows[0].Id : 0;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _sinceLive += TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_sinceLive < LiveInterval)
            return;

        _sinceLive = TimeSpan.Zero;
        if (!IsOpen || !LiveBox.Pressed || _awaitingFirstPage || _loadedQuery is not { } query)
            return;

        // Only a newest-first list of this round with no end time has newer logs to show.
        if (query.Ascending || query.ToSeconds != null || _state == null || _state.RoundId != _state.CurrentRound || query.RoundId != _state.RoundId)
            return;

        _pollGeneration = _searchGeneration;
        QueryRequested?.Invoke(query, Newest(), true);
    }

    public void ShowReport(LogReport report)
    {
        ReportTitle.Text = report.Title;
        _reportFilter = report.Filter;
        ReportFilterButton.Visible = report.Filter != null;
        Report.RemoveAllChildren();
        foreach (var section in report.Sections)
        {
            Report.AddChild(new Label
            {
                Text = section.Title,
                FontColorOverride = Color.FromHex("#9ec5ff"),
                Margin = new Thickness(0, 4, 0, 0),
            });

            foreach (var line in section.Lines)
            {
                var label = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(8, 0, 0, 0) };
                label.SetMessage(FormattedMessage.FromUnformatted(line));
                Report.AddChild(label);
            }

            if (section.Rows == null)
                continue;

            foreach (var row in section.Rows)
            {
                var control = new LogRowControl(Time(row.Date), row) { Margin = new Thickness(8, 0, 0, 0) };
                var picked = row;
                control.OnPressed += _ => Pick(picked);
                Report.AddChild(control);
            }
        }
    }

    /// <summary>Searches for what a report found, such as the players near a moment and the minute around it.</summary>
    private void ApplyReportFilter()
    {
        if (_reportFilter is not { } filter)
            return;

        _chosenPlayers.Clear();
        _chosenPlayers.AddRange(filter.Players);
        _chosenEntities.Clear();
        AllPlayersBox.Pressed = false;
        FromEdit.Text = filter.FromSeconds is { } from ? LogInvestigatorText.RoundTime(TimeSpan.FromSeconds(from)) : string.Empty;
        ToEdit.Text = filter.ToSeconds is { } to ? LogInvestigatorText.RoundTime(TimeSpan.FromSeconds(to)) : string.Empty;
        UpdateChips();
        Search();
    }

    /// <summary>Whether a control is the given one or inside it.</summary>
    private static bool Inside(Control? control, Control ancestor)
    {
        for (var at = control; at != null; at = at.Parent)
        {
            if (at == ancestor)
                return true;
        }

        return false;
    }

    /// <summary>
    /// Starts a new search, unless a filter can't be read, which it says instead of quietly dropping. Load more waits
    /// for its first page, so it never mixes it with the rows shown.
    /// </summary>
    private void Search()
    {
        var error = QueryProblem();
        QueryError.Visible = error != null;
        QueryError.Text = error ?? string.Empty;
        if (error != null)
            return;

        var query = BuildQuery();
        if (NearBox.Pressed && NearPoint() is { } near)
        {
            query.Near = near;
            query.NearRadius = Radius();
        }

        Search(query);
    }

    /// <summary>Starts a new search for this query, as it is; a live refresh reruns the one on screen this way.</summary>
    private void Search(LogQuery query)
    {
        _loadedQuery = query;
        _hasMore = false;
        _awaitingFirstPage = true;
        _searchGeneration++;
        MoreButton.Disabled = true;
        QueryRequested?.Invoke(_loadedQuery, null, false);
    }

    /// <summary>The next page of the search on screen, whatever the filters say now; disabled until that page comes.</summary>
    private void More()
    {
        if (!_hasMore || _rows.Count == 0 || _loadedQuery == null)
            return;

        _hasMore = false;
        MoreButton.Disabled = true;
        QueryRequested?.Invoke(_loadedQuery, _rows[^1].Id, false);
    }

    /// <summary>What stops the filters from being searched, if anything.</summary>
    private string? QueryProblem()
    {
        if (FromEdit.Text.Trim().Length > 0 && LogInvestigatorText.ParseRoundTime(FromEdit.Text) == null)
            return Loc.GetString("wg-log-investigator-bad-time", ("field", Loc.GetString("wg-log-investigator-from")), ("text", FromEdit.Text.Trim()));
        if (ToEdit.Text.Trim().Length > 0 && LogInvestigatorText.ParseRoundTime(ToEdit.Text) == null)
            return Loc.GetString("wg-log-investigator-bad-time", ("field", Loc.GetString("wg-log-investigator-to")), ("text", ToEdit.Text.Trim()));
        if (NearBox.Pressed && NearPoint() == null)
            return Loc.GetString("wg-log-investigator-near-none");
        return null;
    }

    /// <summary>Where the picked log happened: its first entity with a recorded position, players first.</summary>
    private LogPoint? NearPoint()
    {
        if (_selected is not { } row)
            return null;

        var placed = row.Refs.Where(r => r.Map != null && r.X != null && r.Y != null).OrderBy(r => r.Player == null).FirstOrDefault();
        return placed is { Map: { } map, X: { } x, Y: { } y } ? new LogPoint(map, placed.Grid, x, y, row.Date) : null;
    }

    private LogQuery BuildQuery()
    {
        var types = new HashSet<LogType>();
        foreach (var (_, _, typeBoxes) in _categories)
        {
            foreach (var (type, box) in typeBoxes)
            {
                if (box.Pressed)
                    types.Add(type);
            }
        }

        var impacts = _impacts.Where(i => i.Value.Pressed).Select(i => i.Key).ToHashSet();
        return new LogQuery
        {
            RoundId = _state?.RoundId ?? 0,
            FromSeconds = LogInvestigatorText.ParseRoundTime(FromEdit.Text),
            ToSeconds = LogInvestigatorText.ParseRoundTime(ToEdit.Text),
            Types = types.Count == Enum.GetValues<LogType>().Length ? null : types,
            Impacts = impacts.Count == _impacts.Count ? null : impacts,
            Players = _chosenPlayers.ToArray(),
            AllPlayers = AllPlayersBox.Pressed,
            Entities = _chosenEntities.ToArray(),
            Text = string.IsNullOrWhiteSpace(TextBox.Text) ? null : TextBox.Text.Trim(),
            IncludeNonPlayers = NonPlayersBox.Pressed,
            Ascending = OldestFirstBox.Pressed,
        };
    }

    private void UpdateCount()
    {
        var total = _total is { } count
            ? count >= 100_000 ? "100000+" : count.ToString()
            : "?";
        var behind = _state != null && _state.RoundId == _state.CurrentRound
            ? " " + Loc.GetString("wg-log-investigator-behind")
            : string.Empty;
        CountLabel.Text = Loc.GetString("wg-log-investigator-count", ("loaded", _rows.Count), ("total", total)) + behind;
        CountLabel.ToolTip = CountLabel.Text;
    }

    /// <summary>Rebuilds the result list, each log wrapped to the list's width, folding repeats when asked.</summary>
    private void ShowRows()
    {
        Results.RemoveAllChildren();
        _rowControls.Clear();
        foreach (var control in BuildRows(0, _rows.Count))
        {
            _rowControls.Add(control);
            Results.AddChild(control);
        }
    }

    /// <summary>The row controls for the logs from <paramref name="start"/> up to <paramref name="end"/>, folded when asked.</summary>
    private List<LogRowControl> BuildRows(int start, int end)
    {
        var controls = new List<LogRowControl>();
        if (!CollapseBox.Pressed)
        {
            for (var i = start; i < end; i++)
            {
                controls.Add(RowControl(i, 1));
            }

            return controls;
        }

        foreach (var run in LogInvestigatorText.Collapse(_rows.GetRange(start, end - start), CollapseWindow))
        {
            var first = start + run.Start;
            if (run.Count == 1 || _expanded.Contains(first))
            {
                for (var i = 0; i < run.Count; i++)
                {
                    // The first row of an unfolded run folds it back up.
                    controls.Add(RowControl(first + i, 1, i == 0 && run.Count > 1 ? run.Count : 0));
                }
            }
            else
            {
                controls.Add(RowControl(first, run.Count));
            }
        }

        return controls;
    }

    /// <summary>
    /// A row for one log, or for <paramref name="count"/> folded ones from <paramref name="index"/>. With
    /// <paramref name="unfolded"/>, it heads an unfolded run of that many and folds it again when clicked.
    /// </summary>
    private LogRowControl RowControl(int index, int count, int unfolded = 0)
    {
        var row = _rows[index];
        var prefix = count > 1
            ? Loc.GetString("wg-log-investigator-run", ("count", count),
                ("seconds", (int) (_rows[index + count - 1].Date - row.Date).Duration().TotalSeconds))
            : unfolded > 0 ? Loc.GetString("wg-log-investigator-refold", ("count", unfolded)) : null;

        var control = new LogRowControl(Time(row.Date), row, prefix) { Selected = row.Id == _selected?.Id };
        control.OnPressed += _ =>
        {
            // A folded run opens on click; a single row shows its detail.
            if (count > 1)
            {
                // Found again on click: newer logs above it may have moved it down since the row was built.
                _expanded.Add(_rows.IndexOf(row));
                _selected = row;
                ShowRows();
                ShowDetail();
                return;
            }

            if (unfolded > 0)
            {
                _expanded.Remove(_rows.IndexOf(row));
                _selected = row;
                ShowRows();
                ShowDetail();
                return;
            }

            Pick(row);
        };

        return control;
    }

    /// <summary>Shows a log in the detail pane and marks its row.</summary>
    private void Pick(LogRow row)
    {
        _selected = row;
        foreach (var control in _rowControls)
        {
            control.Selected = control.Row.Id == row.Id;
        }

        ShowDetail();
    }

    private string Time(DateTime date)
    {
        return _state?.RoundStart is { } start
            ? LogInvestigatorText.RoundTime(date - start)
            : date.ToLocalTime().ToString("HH:mm:ss");
    }

    private void Copy()
    {
        var text = new StringBuilder();
        foreach (var row in _rows)
        {
            text.Append(Time(row.Date)).Append(" [").Append(row.Type).Append("] ").AppendLine(row.Message);
        }

        _clipboard.SetText(text.ToString());
    }

    #endregion

    #region Selected log

    private void ShowDetail()
    {
        RefActions.RemoveAllChildren();
        var detail = new FormattedMessage();
        if (_selected is not { } row)
        {
            detail.AddText(Loc.GetString("wg-log-investigator-pick-row"));
            Detail.SetMessage(detail);
            return;
        }

        detail.PushColor(LogInvestigatorStyle.ImpactColor(row.Impact));
        detail.AddText($"{Time(row.Date)} [{row.Type}] {row.Impact}");
        detail.Pop();
        detail.PushNewline();
        detail.AddText(row.Message);
        Detail.SetMessage(detail);

        var netIds = LogInvestigatorText.EntityIds(row.Message);
        foreach (var reference in row.Refs)
        {
            RefActions.AddChild(RefRow(row, reference, netIds.GetValueOrDefault(reference.Id, reference.Id)));
        }
    }

    /// <summary>A line of buttons for one entity the selected log names.</summary>
    private Control RefRow(LogRow row, LogRef reference, int net)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        box.AddChild(new Label
        {
            Text = $"{reference.Key}: {reference.Name ?? reference.Id.ToString()}",
            ClipText = true,
            HorizontalExpand = true,
            MinWidth = 120,
        });

        AddButton(box, "wg-log-investigator-filter", () =>
        {
            if (reference.Player is { } player)
            {
                if (!_chosenPlayers.Contains(player))
                    _chosenPlayers.Add(player);
            }
            else if (!_chosenEntities.Contains(reference.Id))
            {
                _chosenEntities.Add(reference.Id);
            }

            UpdateChips();
        });
        // Entity ids are reused across rounds: following or viewing one from another round finds something else.
        if (_state != null && _state.RoundId == _state.CurrentRound)
        {
            AddButton(box, "wg-log-investigator-follow", () => _console.ExecuteCommand($"follow {net}"));
            AddButton(box, "wg-log-investigator-vv", () => _console.ExecuteCommand($"vv {net}"));
        }

        if (reference is { Map: { } map, X: { } x, Y: { } y })
        {
            AddButton(box, "wg-log-investigator-nearby", () =>
                ReportRequested?.Invoke(LogReportKind.Nearby, BuildQuery(), new LogPoint(map, reference.Grid, x, y, row.Date), Radius()));
        }

        if (reference.Player is { } timelinePlayer)
        {
            AddButton(box, "wg-log-investigator-timeline", () =>
            {
                var query = BuildQuery();
                query.Players = new[] { timelinePlayer };
                ReportRequested?.Invoke(LogReportKind.Timeline, query, null, Radius());
            });
        }

        return box;
    }

    private static void AddButton(BoxContainer box, string text, Action action)
    {
        var button = new Button { Text = Loc.GetString(text), StyleClasses = { "OpenBoth" } };
        button.OnPressed += _ => action();
        box.AddChild(button);
    }

    private int Radius()
    {
        return int.TryParse(RadiusEdit.Text, out var radius) ? Math.Clamp(radius, 1, 200) : 15;
    }

    #endregion

    #region Filters

    private void ShowPlayerMatches()
    {
        PlayerMatches.RemoveAllChildren();
        var search = PlayerSearch.Text.Trim();
        foreach (var player in _players)
        {
            if (_chosenPlayers.Contains(player.Id))
                continue;

            if (search.Length > 0
                && !player.Username.Contains(search, StringComparison.OrdinalIgnoreCase)
                && !(player.Character?.Contains(search, StringComparison.OrdinalIgnoreCase) ?? false))
                continue;

            var button = new Button { Text = PlayerName(player.Id), ClipText = true, StyleClasses = { "OpenBoth" } };
            var id = player.Id;
            button.OnPressed += _ =>
            {
                _chosenPlayers.Add(id);
                UpdateChips();
            };
            PlayerMatches.AddChild(button);
        }
    }

    private void UpdateChips()
    {
        PlayerChips.RemoveAllChildren();
        foreach (var player in _chosenPlayers)
        {
            var id = player;
            PlayerChips.AddChild(Chip(PlayerName(player), () =>
            {
                _chosenPlayers.Remove(id);
                UpdateChips();
            }));
        }

        EntityChips.RemoveAllChildren();
        foreach (var entity in _chosenEntities)
        {
            var id = entity;
            EntityChips.AddChild(Chip(Loc.GetString("wg-log-investigator-entity", ("id", entity)), () =>
            {
                _chosenEntities.Remove(id);
                UpdateChips();
            }));
        }

        ShowPlayerMatches();
    }

    private string PlayerName(Guid id)
    {
        var player = _players.FirstOrDefault(p => p.Id == id);
        if (player == null)
            return id.ToString();

        return player.Character != null ? $"{player.Character} ({player.Username})" : player.Username;
    }

    private static Control Chip(string text, Action remove)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        box.AddChild(new Label { Text = text, ClipText = true, HorizontalExpand = true });
        var button = new Button { Text = "✕", StyleClasses = { "OpenLeft" } };
        button.OnPressed += _ => remove();
        box.AddChild(button);
        return box;
    }

    private void BuildImpacts()
    {
        foreach (var impact in Enum.GetValues<LogImpact>().OrderBy(i => i))
        {
            var button = new Button
            {
                Text = impact.ToString(),
                ToggleMode = true,
                Pressed = true,
                StyleClasses = { "OpenBoth" },
                ModulateSelfOverride = LogInvestigatorStyle.ImpactColor(impact),
            };
            _impacts[impact] = button;
            ImpactButtons.AddChild(button);
        }
    }

    private void BuildCategories()
    {
        foreach (var category in _proto.EnumeratePrototypes<WGLogCategoryPrototype>().OrderBy(c => c.Order))
        {
            var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
            var box = new CheckBox { Text = Loc.GetString(category.Name), Pressed = true, HorizontalExpand = true };
            var expand = new Button { Text = "▸", StyleClasses = { "OpenLeft" } };
            header.AddChild(box);
            header.AddChild(expand);
            CategoryTree.AddChild(header);

            var children = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Visible = false, Margin = new Thickness(16, 0, 0, 0) };
            var types = new List<(LogType, CheckBox)>();
            foreach (var type in category.Types)
            {
                var typeBox = new CheckBox { Text = type.ToString(), Pressed = true };
                typeBox.OnToggled += _ => box.Pressed = types.Any(t => t.Item2.Pressed);
                types.Add((type, typeBox));
                children.AddChild(typeBox);
            }

            CategoryTree.AddChild(children);
            box.OnToggled += args =>
            {
                foreach (var (_, typeBox) in types)
                {
                    typeBox.Pressed = args.Pressed;
                }
            };
            expand.OnPressed += _ =>
            {
                children.Visible = !children.Visible;
                expand.Text = children.Visible ? "▾" : "▸";
            };
            _categories.Add((category, box, types));
        }
    }

    private void BuildPresets()
    {
        AddPreset("wg-log-investigator-preset-all", null);
        AddPreset("wg-log-investigator-preset-combat", "WGLogCombat");
        AddPreset("wg-log-investigator-preset-comms", "WGLogChat");
        AddPreset("wg-log-investigator-preset-ships", "WGLogShips");
        AddPreset("wg-log-investigator-preset-economy", "WGLogEconomy");
    }

    /// <summary>A button that shows only one category (or all of them) and searches.</summary>
    private void AddPreset(string name, string? category)
    {
        var button = new Button { Text = Loc.GetString(name), StyleClasses = { "OpenBoth" } };
        button.OnPressed += _ =>
        {
            foreach (var (proto, box, types) in _categories)
            {
                var on = category == null || proto.ID == category;
                box.Pressed = on;
                foreach (var (_, typeBox) in types)
                {
                    typeBox.Pressed = on;
                }
            }

            Search();
        };
        Presets.AddChild(button);
    }

