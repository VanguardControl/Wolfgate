"""Writes Resources/Prototypes/_WF/Blueprints/techweb.yml: one hunt-only pattern per tier-2 and tier-3 technology.

A technology named by a pattern can't be researched with points; the hunt unlocks it instead. Rerun after techweb
changes: python Tools/_WF/Blueprints/gen_techweb_patterns.py
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
PROTOS = os.path.join(ROOT, 'Resources', 'Prototypes')
OUT = os.path.join(PROTOS, '_WF', 'Blueprints', 'techweb.yml')

# Technologies left out of the hunt (none: tier 1 is free and points unlock nothing).
EXEMPT: set[str] = set()

# Tier 2 is a Recovered (I) hunt. A tier-3 technology at or above this cost is Forgotten (III); below it, Lost (II).
FORGOTTEN_COST = 40000


def blocks(kind):
    for dp, _, files in os.walk(PROTOS):
        for f in files:
            if not f.endswith('.yml'):
                continue
            text = open(os.path.join(dp, f), encoding='utf-8', errors='ignore').read()
            for block in re.split(r'^- type: ', text, flags=re.M)[1:]:
                if block.startswith(kind + '\n') or block.startswith(kind + '\r\n'):
                    yield block


def field(block, key):
    m = re.search(rf'^  {key}: *(.*?)\s*(#.*)?$', block, re.M)
    return m.group(1).strip() if m else None


def items(block, key):
    if f'\n  {key}:' not in block:
        return []
    out = []
    for line in block.split(f'\n  {key}:', 1)[1].splitlines()[1:]:
        m = re.match(r'^  - (\S+)', line)
        if m:
            out.append(m.group(1))
        elif line.strip() and not line.strip().startswith('#'):
            break
    return out


def main():
    results = {}
    for block in blocks('latheRecipe'):
        rid, res = field(block, 'id'), field(block, 'result')
        if rid and res:
            results[rid] = res

    techs = []
    for block in blocks('technology'):
        tid = field(block, 'id')
        if not tid or field(block, 'tier') not in ('2', '3') or field(block, 'hidden') == 'true' or tid in EXEMPT:
            continue
        recipes = items(block, 'recipeUnlocks')
        icon = field(block, 'entityIcon') or next((results[r] for r in recipes if r in results), None)
        if not icon:
            print(f'skipped {tid}: nothing to show as its icon', file=sys.stderr)
            continue
        cost = int(field(block, 'cost') or 10000)
        tier = 1 if field(block, 'tier') == '2' else 3 if cost >= FORGOTTEN_COST else 2
        techs.append((field(block, 'discipline'), tier, cost, tid, field(block, 'name'), icon))

    techs.sort()
    lines = [
        '# Generated by Tools/_WF/Blueprints/gen_techweb_patterns.py. Don\'t edit by hand.',
        '# Every tier-2 and tier-3 technology is hunt-only: its pattern unlocks it, points can\'t.',
        '',
    ]
    discipline = None
    for disc, tier, cost, tid, name, icon in techs:
        if disc != discipline:
            discipline = disc
            lines += [f'# {disc}', '']
        lines += [
            '- type: wfBlueprintPattern',
            f'  id: WFTech{tid}',
            f'  name: {name}',
            f'  tier: {tier}',
            f'  icon: {icon}',
            f'  technology: {tid}',
            '',
        ]
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(f'{len(techs)} technologies written to {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
